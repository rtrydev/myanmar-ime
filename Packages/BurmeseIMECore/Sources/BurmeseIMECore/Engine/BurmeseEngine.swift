import Foundation

/// Tunable knobs for the ranking comparators.
///
/// `alpha` is the weight on the LM log-prob in the composite score
/// `log(rank_score) + α · lmLogProb` used by both grammar and lexicon
/// comparators. 0.4 is the midpoint of the 0.3–0.5 range suggested by
/// prior IME tuning literature; lower α biases toward parser/lexicon
/// frequency, higher α biases toward the LM.
public struct RankingTuning: Sendable {
    public let alpha: Double

    public init(alpha: Double = 0.4) {
        self.alpha = alpha
    }

    public static let `default` = RankingTuning()
}

/// The main composition engine for the Burmese IME.
///
/// Manages the composition buffer, generates candidates from grammar parsing
/// and lexicon lookup, and handles commit/cancel operations.
///
/// Ranking order: grammar legality > alias cost > LM log-prob > parser score
/// > lexicon frequency. The LM replaces the earlier hand-tuned bigram
/// boost — see `Packages/BurmeseIMECore/Sources/BurmeseIMECore/LanguageModel/FORMAT.md`.
///
/// The implementation is split across topic-focused extension files under
/// `Engine/`:
///
/// - `BurmeseEngine+Ranking.swift` — comparators, composite score, ya-pin
///   / alias promotion, LM-margin pruning.
/// - `BurmeseEngine+FrozenPrefix.swift` — prefix / LM-score caching,
///   syllable-safe split finding.
/// - `BurmeseEngine+Punctuation.swift` — mapped-punctuation handling,
///   literal-head splitting, creaky-tone detection.
/// - `BurmeseEngine+MidBufferDigits.swift` — mid-buffer digit extraction
///   / splicing, tail letter-run composition, digit conversion.
/// - `BurmeseEngine+Normalization.swift` — parser-input normalization,
///   acceptable-parse predicates, stack inference, ya-pin/ya-yit
///   normalization, ZWSP handling.
/// - `BurmeseEngine+Sanitizers.swift` — aa-shape correction, orphan
///   ZWNJ drops, Pali/bare-vowel overrides, polluted-surface filter.
public final class BurmeseEngine: @unchecked Sendable {

    /// Number of N-best parses requested from `SyllableParser` per keystroke.
    /// This is the pool the LM re-ranks; candidates ranked beyond this by the
    /// parser's own score never reach the LM, so it must be large enough to
    /// include plausible medial/onset alternates. The parser's internal beam
    /// scales to `max(budget × 16, 64)`, so a budget of 64 keeps the beam
    /// ≈1024 — still comfortably sub-millisecond on an M-series Mac.
    private static let grammarCandidateBudget = 32

    /// Expanded N-best budget for readings where `h` participates in a
    /// high-ambiguity cluster: it may be an aspirated onset marker, a
    /// ha-medial, or part of a following consonant run. A narrow DP beam
    /// drops LM-favored siblings such as `than3hly2in` and `ahaakhyain`
    /// before the ranker can compare them, while ordinary buffers should
    /// keep the smaller hot-path budget.
    private static let expandedGrammarCandidateBudget = 48

    /// Budget for the second `parseCandidates` call that
    /// `inferImplicitStackMarkers` makes when an implicit stack site is
    /// detected. The primary parse already enumerates every unstacked
    /// interpretation, so this pass only needs to surface the stacked
    /// top pick plus a small set of medial alternates. A narrower beam
    /// here is the single biggest lever on the `long` / `incremental`
    /// regression that task 09 introduced — the second parse is what
    /// ~doubled per-keystroke cost on kinzi-bearing buffers. The merge
    /// only needs the top stacked pick plus its nearest alternate.
    private static let stackInferenceBudget = 2

    /// Maximum natural-log-probability gap a candidate may trail the best
    /// LM-ranked candidate before being dropped. 8 ≈ factor ~3000×; well
    /// below that and the candidate is almost certainly nonsense noise
    /// generated by the parser. Keeps the panel to plausible picks only.
    /// Used as the fallback when no `IMESettings` instance is supplied.
    private static let lmPruneMarginDefault: Double = 8.0

    /// LM log-prob gap above which the LM signal dominates over the
    /// composite `log(rank_score) + α·lm` in the grammar comparator. At
    /// 1 nat (≈ factor 2.7× in probability), the LM is differentiating
    /// candidates strongly enough that a lexicon-absorbed score shouldn't
    /// be able to override it — otherwise ya-pin surfaces (LM-preferred
    /// but lexicon-penalty-suppressed) lose to ya-yit siblings that get
    /// a big absorption boost. For gaps under this threshold, composite
    /// falls through and lexicon-anchored surfaces can tip close races
    /// toward the lexicon-validated form (e.g. `an` → `အံ`).
    internal static let lmDominanceThreshold: Double = 1.0

    internal let parser: SyllableParser
    private let candidateStore: any CandidateStore
    /// Word-lattice / segmentation decoder layered on top of the parser
    /// + lexicon. Initialised eagerly because it captures the LM and
    /// store references that are passed in at engine-init time anyway.
    /// Kept as an implicit-`let` rather than `Optional` so callers can
    /// always invoke it; an empty store / null LM degrade it into a
    /// pass-through that returns `[]` quickly.
    private let latticeDecoder: WordLatticeDecoder
    private let historyStore: any UserHistoryStore
    internal let languageModel: any LanguageModel

    /// Sliding-window threshold for the full N-best parse. When the
    /// normalized buffer exceeds this, everything before the trailing
    /// window is rendered once via a cheap single-best parse and cached;
    /// only the tail is re-parsed on each keystroke. The window covers
    /// `maxOnsetLen + maxVowelLen` plus a safety margin so no rule can
    /// span the prefix/tail boundary.
    ///
    /// Boundary guards reject known cross-boundary contexts (`a...`
    /// connectors and `...in<C>` coda sites) rather than widening this
    /// window, which keeps the incremental benchmark within its p95/p99
    /// budget.
    private let compositionWindowSize: Int

    /// Small LRU (most-recent-first). Survives backspace-then-retype without
    /// re-parsing the frozen prefix. Capacity is deliberately tiny — each
    /// entry is one parse plus its branches (typically K=1), and linear scan
    /// at this size is cheaper than dictionary overhead.
    internal var prefixCache: [FrozenPrefixCache] = []
    internal let cacheLock = NSLock()

    private struct StackInferenceParseCache {
        let input: String
        let isFullBuffer: Bool
        let parses: [SyllableParse]
    }

    private var stackInferenceParseCache: [StackInferenceParseCache] = []
    private static let maxStackInferenceParseCache = 16

    /// LRU cache for the strict (non-liberal) `parseCandidates` calls
    /// the engine makes per keystroke against the active tail and the
    /// full normalized buffer (TASK-051). The active-tail parse at
    /// line ~816 and any window-fallback re-parse at line ~1080
    /// dominate per-keystroke latency once the tail contains
    /// nga-asat-emitting vowel rules in chains; without this cache
    /// each iteration of a steady-state buffer (the bench's
    /// `vowel_rule_chain_*` scenarios) repeats the same parse work.
    /// Keyed by `(input, maxResults, isFullBuffer)` — `allowLiberalStacks`
    /// is implicitly `false` here, since the liberal path lives in
    /// `stackInferenceParseCache`.
    private struct GrammarParseCache {
        let input: String
        let maxResults: Int
        let isFullBuffer: Bool
        let parses: [SyllableParse]
    }
    private var grammarParseCache: [GrammarParseCache] = []
    private static let maxGrammarParseCache = 16

    /// Window-split decision cache (TASK-051). For long buffers
    /// `findSyllableSafeSplit` walks up to ~24 candidate split
    /// positions, each running 4 parser passes — ~26ms per call on
    /// the `vowel_rule_chain_aing_8` shape where every `aing`-`g`
    /// boundary is structurally unsafe and the function falls
    /// through to the target. Most of the work is wasted: the same
    /// `(normalized, lowerBound)` pair always returns the same
    /// answer. Memoising it eliminates the per-keystroke walk on
    /// steady-state buffers. Capacity 8 covers the realistic
    /// per-engine working set (one in-flight buffer plus its recent
    /// length-extended siblings).
    private struct WindowSplitCache {
        let normalized: String
        let lowerBound: Int
        let split: Int
    }
    private var windowSplitCache: [WindowSplitCache] = []
    private static let maxWindowSplitCache = 8


    /// History of anchors (checkpoints) ordered by `normalized.count`.
    /// When the latest/deepest anchor's tail can't parse standalone
    /// (e.g. a single "a" or ":"), we fall back to an earlier checkpoint
    /// whose tail is long enough to parse. This keeps the rendered
    /// prefix stable even across intermediate strokes where the tail
    /// alone is ambiguous.
    private var anchorHistory: [PrefixAnchor] = []
    private static let maxAnchorHistory = 32

    /// Last alias-normalized lookup key produced by `update`. Captured under
    /// `cacheLock` so `recordSelection` can write the same key the lexicon
    /// and history stores would have seen on lookup — keeping write/read
    /// symmetric without plumbing the key through `CompositionState`.
    internal var lastHistoryKey: String = ""

    /// Upper bound on the active-tail length before the frozen prefix is
    /// extended forward. Keeping this larger than `compositionWindowSize`
    /// means an already-chosen prefix stays stable for many keystrokes —
    /// the committed portion the user sees doesn't shift as they type.
    /// Only when the tail reaches this size do we advance the split point.
    private static let maxActiveTailSize = 40

    /// Roman-input length past which a previously-rendered top candidate
    /// is treated as "committed" and will not be re-parsed on subsequent
    /// keystrokes. Below this, the engine always performs a fresh full-
    /// buffer parse so that early ambiguous picks (e.g. `k`, `kw`, `kwy`
    /// before medials can be disambiguated) can be overwritten by a
    /// clearly better interpretation once enough characters exist. At or
    /// above this length, the LM had real evidence when selecting the
    /// anchor, so we lock it to prevent the committed portion from
    /// silently drifting under the user.
    /// Fallback used when no `IMESettings` instance is supplied.
    private static let anchorCommitThresholdDefault = 8

    /// Minimum normalised-reading length before the lattice decoder
    /// runs. Below this, the parser + whole-buffer lexicon path is
    /// already optimal and lattice injection only invites rare
    /// lexicon surfaces (tone-variant `ကျွန်တော့်` vs `ကျွန်တော်`
    /// being the canonical example, winning the coda-only
    /// single-scalar LM tiebreak by a narrow margin) to outrank clean
    /// parser output. 12 is just above the single-word-plus-particle
    /// ceiling (`kwyantaw` = 8 chars, `kwyantawka` = 10) and well
    /// below where multi-word debt kicks in (~15+ chars).
    private static let latticeMinReadingLen = 12

    /// Maximum log-prob gap a lattice candidate can trail the
    /// lattice top before being dropped at engine-injection time.
    /// 3 nats ≈ factor 20×; anything weaker than that is a tail
    /// variant (retroflex `ဌ`, punctuation artefact) that the
    /// anchor history would promote on subsequent keystrokes if we
    /// kept it in the panel at an intermediate buffer length.
    private static let latticeLmInjectionMargin: Double = 3.0

    /// Page size for candidate display. Fallback used when no `IMESettings`
    /// instance is supplied.
    public static let candidatePageSizeDefault = 9

    internal let settings: IMESettings?
    internal let tuning: RankingTuning
    /// Digit boundaries passed inward from `extractMidBufferDigits` so
    /// that `inferImplicitStackMarkers` can avoid inserting `+` across a
    /// position where the user explicitly placed an ASCII digit (task 01).
    /// Set immediately before the digit-extraction recursive `update()`
    /// call and cleared after it returns. Never read on the windowed path
    /// (offsets only apply to the full cleaned buffer, not the active tail).
    private var midDigitBoundaries: Set<Int> = []

    /// Live-read wrapper. Falls back to the static default when no settings
    /// instance is wired; otherwise reflects the shared UserDefaults value,
    /// so the IMK extension sees changes without an engine rebuild.
    public var candidatePageSize: Int {
        settings?.candidatePageSize ?? Self.candidatePageSizeDefault
    }
    internal var lmPruneMargin: Double {
        settings?.lmPruneMargin ?? Self.lmPruneMarginDefault
    }
    private var anchorCommitThreshold: Int {
        settings?.anchorCommitThreshold ?? Self.anchorCommitThresholdDefault
    }
    internal var burmesePunctuationEnabled: Bool {
        settings?.burmesePunctuationEnabled ?? false
    }

    public init(
        candidateStore: any CandidateStore = EmptyCandidateStore(),
        historyStore: any UserHistoryStore = EmptyUserHistoryStore(),
        languageModel: any LanguageModel = NullLanguageModel(),
        settings: IMESettings? = nil,
        tuning: RankingTuning = .default
    ) {
        let useClusterAliases = settings?.clusterAliasesEnabled ?? true
        let parser = SyllableParser(useClusterAliases: useClusterAliases)
        self.parser = parser
        self.candidateStore = candidateStore
        self.historyStore = historyStore
        self.languageModel = languageModel
        self.latticeDecoder = WordLatticeDecoder(
            parser: parser,
            candidateStore: candidateStore,
            languageModel: languageModel,
            tuning: tuning
        )
        self.settings = settings
        self.tuning = tuning
        // Active-tail size in Roman chars. Once the buffer exceeds this,
        // everything before a syllable-safe boundary is parsed once and
        // cached (the "frozen prefix"); subsequent keystrokes only re-parse
        // the trailing window. A naïve character-count split was the source
        // of the earlier "garbage variants past the threshold" bug — the
        // split now snaps back to the nearest position where the prefix
        // parses fully legally on its own, so it never cuts mid-syllable.
        self.compositionWindowSize = 18
    }

    private static func grammarCandidateBudget(for normalizedInput: String) -> Int {
        if normalizedInput.contains("khy") || normalizedInput.contains("hly") {
            return expandedGrammarCandidateBudget
        }
        return grammarCandidateBudget
    }

    private static let composingPunctOnlyChars: Set<Character> = ["+", "*", "'", ":", "."]

    /// True when every character in `buffer` is a composing-punctuation
    /// modifier (`'`, `+`, `*`, `:`, `.`). Used to short-circuit the
    /// pipeline for lone-modifier buffers that the parser collapses to
    /// empty / no candidates. See task 04.
    internal static func isComposingPunctOnlyBuffer(_ buffer: String) -> Bool {
        guard !buffer.isEmpty else { return false }
        return buffer.allSatisfy { composingPunctOnlyChars.contains($0) }
    }

    /// Update the composition state based on the current buffer and context.
    /// Called on every keystroke that modifies the buffer.
    ///
    /// Public entry point. Delegates the heavy pipeline to
    /// `updateInternal` and then applies the literal-fallback
    /// post-processing (TASK-043) so the user always sees a
    /// commit-as-typed escape hatch in the candidate panel when the
    /// input has no clean lexicon hit. Recursive paths inside the
    /// pipeline call `updateInternal` directly to avoid double-
    /// applying the fallback to intermediate buffer slices.
    public func update(buffer: String, context: [String]) -> CompositionState {
        let state = updateInternal(buffer: buffer, context: context)
        // `state.rawBuffer` is already the lowercased displayBuffer
        // (set by `updateInternal` for the active-composition paths,
        // empty for the empty-input early return). Reuse it instead of
        // lowercasing `buffer` again on every keystroke.
        var injected = injectLiteralFallback(state: state, rawBuffer: state.rawBuffer)
        // TASK-045: re-run the doubled-coda chain sanitizer with the
        // literal fallback in place. Inside `updateInternal` the
        // sanitizer's "preserve when no clean sibling exists"
        // fallback retains every violator because the only
        // candidates at that point are parser/grammar surfaces, all
        // of which can carry the doubled-coda chain when the buffer
        // contains a doubled-`e`-rule on a non-trivial prefix
        // (`ka+ee`, `kar+ee`, `u+ee`, …). Once the literal-tail
        // fallback is injected the panel has a verifiably clean
        // sibling, and the filter pass can promote the legal
        // candidates above the violators.
        injected.candidates = Self.sanitizeDoubledCodaChain(injected.candidates)
        // TASK-052: same pattern — re-run the digit-orphan-asat
        // sanitizer with the literal fallback in place. Inside
        // `updateInternal` the panel may not yet contain a candidate
        // free of the `<digit>(1021)?103A` adjacency (every parser
        // surface for a `<digit><vowel-letter>*` shape carries the
        // orphan-anchor cluster). Once the literal-fallback (raw
        // buffer verbatim) lands, the filter sees a clean sibling and
        // can promote it past the malformed Myanmar candidates.
        injected.candidates = Self.sanitizeDigitOrphanAsat(injected.candidates)
        // TASK-057: same pattern — re-run the tone-orphan-asat
        // sanitizer with the literal fallback in place. Pre-fix the
        // engine fabricated `<tone> 1021 103A` for inputs like
        // `kar:.*`, `ka:*`, `o:.*` where the orphan-mark anchor
        // injector wedged a phantom independent-vowel between the
        // tone closure and the unanchored asat. Once the literal
        // fallback is injected the panel has a clean sibling, so the
        // filter pass can promote it past the malformed Myanmar
        // candidates.
        injected.candidates = Self.sanitizeToneOrphanAsat(injected.candidates)
        // TASK-069: same pattern — re-run the bare-indep-vowel-asat
        // sanitizer with the literal fallback in place. Pre-fix the
        // engine surfaced `1021 103A` (bare `အ` + asat) at rank 0 for
        // inputs like `a*`, `aa*`, `ka+a*`, `a*ka`, `a*ya`. The
        // legality scan accepts the shape because `isConsonantBase`
        // admits U+1021 as a base, but `အ` is the vowel-only consonant
        // whose inherent vowel cannot be legitimately suppressed.
        // Once the literal fallback is injected the panel has a clean
        // sibling so the filter pass can drop the malformed Myanmar.
        injected.candidates = Self.sanitizeBareIndepVowelAsat(injected.candidates)
        // TASK-056: same pattern — re-run the interleaved-composing-
        // punct sanitizer with the literal fallback in place. The
        // doubled `**`, `''`, `::`, `..` runs (and trailing-singleton
        // `'`) leak literal ASCII scalars between Myanmar scalars
        // through the materialize / affix-merge path; once the
        // literal fallback is injected the panel has a clean sibling
        // (the raw buffer verbatim) so the filter pass can drop the
        // violating Myanmar candidate without leaving the panel
        // empty. Trailing punct (no Myanmar to the right) is still
        // permitted by the predicate.
        injected.candidates = Self.sanitizeInterleavedComposingPunct(injected.candidates)
        // TASK-030: deliberately do NOT run the multi-cluster
        // sanitizer here. Running it post-fallback (when the literal
        // raw buffer has already been injected as a "clean" sibling)
        // would drop every violator-carrying Myanmar candidate and
        // leave only the literal at rank 0. That's the correct
        // outcome for short bug-class buffers (`kayoo`, `kayii`, …)
        // but breaks mid-typing of a longer sentence
        // (`ComprehensiveRanking.sentence_longArticle_literaryInfluence`,
        // prefixes `thueiooz`/`thueiooza`/…), where the violator
        // surface is a multi-anchor parse whose orphan-anchor sub-
        // cluster will be resolved by the next keystroke. The fix
        // for the bug class instead lives at the Class A literal-
        // promotion gate, which uses the tighter
        // `surfaceIsWhollyMultiClusterOnSingleAnchor` predicate to
        // distinguish "whole-buffer violator" (promote literal) from
        // "multi-syllable surface with one orphan sub-cluster"
        // (leave at rank 0; the next keystroke fixes it).
        return injected
    }

    /// TASK-033: detect a buffer of shape `<letter>+'{2,}<letter>+`
    /// (a run of two-or-more contiguous `'` chars sitting BETWEEN two
    /// ASCII-letter runs). The TASK-056 sanitizer correctly drops
    /// every Myanmar candidate carrying the doubled-apostrophe leak,
    /// but every parser candidate for these buffers carries the leak
    /// — so the sanitizer's "preserve violators when nothing clean
    /// exists" path keeps the literal at rank 0 with NO Burmese
    /// sibling reachable. The fix collapses the `''+` run to a single
    /// `'` (the parser's soft-separator role) before parsing, so the
    /// resulting candidate panel matches the single-apostrophe sibling
    /// surface. The literal raw buffer is still added by
    /// `injectLiteralFallback` as a lower-rank fallback.
    ///
    /// Boundary cases (`<lhs>'`, `'<rhs>`, `<lhs>''`, `''<rhs>`) do
    /// NOT match this predicate — the run must sit BETWEEN two letter
    /// runs.
    internal static func collapsedDoubledMidBufferApostrophes(
        _ buffer: String
    ) -> String? {
        guard buffer.contains("''") else { return nil }
        let chars = Array(buffer)
        var anyMatch = false
        var collapsed: [Character] = []
        collapsed.reserveCapacity(chars.count)
        var i = 0
        while i < chars.count {
            let c = chars[i]
            guard c == "'" else {
                collapsed.append(c)
                i += 1
                continue
            }
            // Walk the apostrophe run.
            var runEnd = i
            while runEnd < chars.count, chars[runEnd] == "'" {
                runEnd += 1
            }
            let runLen = runEnd - i
            // Must be flanked by letters on both sides.
            let hasLetterLeft = i > 0
                && Self.isAsciiLetterChar(chars[i - 1])
            let hasLetterRight = runEnd < chars.count
                && Self.isAsciiLetterChar(chars[runEnd])
            if hasLetterLeft && hasLetterRight && runLen >= 2 {
                anyMatch = true
                collapsed.append("'")
            } else {
                for _ in 0..<runLen { collapsed.append("'") }
            }
            i = runEnd
        }
        return anyMatch ? String(collapsed) : nil
    }

    @inline(__always)
    private static func isAsciiLetterChar(_ c: Character) -> Bool {
        guard c.unicodeScalars.count == 1, let scalar = c.unicodeScalars.first else {
            return false
        }
        let v = scalar.value
        return (v >= 0x61 && v <= 0x7A) || (v >= 0x41 && v <= 0x5A)
    }

    /// Pipeline implementation; produces the raw `CompositionState`
    /// without the literal-fallback wrapper. Recursive entries inside
    /// the engine (`englishContractionState`, mid-buffer digit /
    /// embedded-punct splits) call this method so the literal is only
    /// considered once, against the original outer buffer.
    internal func updateInternal(buffer: String, context: [String]) -> CompositionState {
        guard !buffer.isEmpty else {
            cacheLock.lock()
            anchorHistory.removeAll()
            stackInferenceParseCache.removeAll()
            grammarParseCache.removeAll()
            windowSplitCache.removeAll()
            lastHistoryKey = ""
            cacheLock.unlock()
            return CompositionState(committedContext: context)
        }
        let displayBuffer = buffer.lowercased()
        // Task 04: a buffer made up entirely of composing-modifier
        // punctuation (`'`, `+`, `*`, `.`, `:`, individually or
        // repeated) has no Myanmar interpretation — the parser strips
        // leading/trailing `+`, the `'` rule yields empty output, and
        // `*` / `.` / `:` outside a vowel suffix can't anchor any
        // legal surface. Emit a literal-passthrough candidate so the
        // user can commit the typed character verbatim instead of
        // facing an empty panel or accidentally committing
        // `Candidate(surface: "")`. Buffers with any letter or digit
        // fall through to the regular pipeline (the parser handles
        // `'a`, `'thar`, `+thar` correctly via the connector rules).
        if Self.isComposingPunctOnlyBuffer(displayBuffer) {
            return CompositionState(
                rawBuffer: displayBuffer,
                selectedCandidateIndex: 0,
                candidates: [Candidate(
                    surface: displayBuffer,
                    reading: displayBuffer,
                    source: .grammar,
                    score: 0
                )],
                committedContext: context
            )
        }
        // TASK-021: Letter-flanked apostrophes that match English
        // contraction shapes (`don't`, `can't`, `it's`, `we're`, …)
        // must surface as a literal candidate at rank 0 so the user
        // can commit the typed contraction as English text. The
        // null-vowel connector rule would otherwise silently swallow
        // the apostrophe and concatenate the surrounding letters.
        if Self.englishContractionApostropheIndex(in: displayBuffer) != nil {
            return englishContractionState(buffer: displayBuffer, context: context)
        }
        // TASK-033: a run of two-or-more `'` between two letter runs
        // (`thar''mar`, `kar'''par`) collapses to a single `'` for
        // parser consumption. The TASK-056 sanitizer drops every
        // Myanmar candidate carrying the literal `''` leak; without
        // this normalisation the panel is left with only the
        // ASCII-literal raw buffer. Collapsing here lets the parser
        // produce the clean Burmese sibling under the
        // `'`-soft-separator path; the verbatim raw buffer is added
        // back by `injectLiteralFallback` as a lower-rank fallback.
        if let collapsed = Self.collapsedDoubledMidBufferApostrophes(displayBuffer) {
            var state = updateInternal(buffer: collapsed, context: context)
            state.rawBuffer = displayBuffer
            // Carry the user's full buffer through as the candidate
            // reading so `recordSelection` keys history on the
            // original keystrokes. The candidate surfaces inherit
            // from the `'`-collapsed parse.
            state.candidates = state.candidates.map { cand in
                Candidate(
                    surface: cand.surface,
                    reading: displayBuffer,
                    source: cand.source,
                    score: cand.score
                )
            }
            cacheLock.lock()
            lastHistoryKey = Romanization.aliasReading(displayBuffer)
            cacheLock.unlock()
            return state
        }
        // Task 10: Peel mid-buffer ASCII digits (letter-digit-letter) off
        // the buffer before the rest of the pipeline runs, then splice
        // them back into each candidate surface at the scalar position
        // corresponding to the letters typed before the digit. Without
        // this, `splitComposablePrefix` breaks at the digit and the
        // post-digit letters fall back to ZWNJ + dependent-mark orphans.
        let (midCleanedBuffer, midInsertions) =
            Self.extractMidBufferDigits(displayBuffer)
        if !midInsertions.isEmpty {
            // Thread the digit boundary offsets into inferImplicitStackMarkers
            // so it does not insert `+` across positions where the user placed
            // a digit — the digit is a hard syllable break (task 01).
            midDigitBoundaries = Set(midInsertions.map(\.offset))
            var state = updateInternal(buffer: midCleanedBuffer, context: context)
            midDigitBoundaries = []
            state.rawBuffer = displayBuffer
            let spliced = spliceMidBufferDigits(
                into: state.candidates,
                cleaned: midCleanedBuffer,
                insertions: midInsertions
            )
            // The inner `update` was keyed on the digit-stripped buffer;
            // its candidate readings cover only the letters and its
            // `lastHistoryKey` was set from the same active alias. Carry
            // the user's full buffer through both so `recordSelection`
            // doesn't store the spliced surface under a truncated key
            // (task 05 follow-up — the original fix only patched the
            // punct-split recursion paths).
            state.candidates = spliced.map { cand in
                Candidate(
                    surface: cand.surface,
                    reading: displayBuffer,
                    source: cand.source,
                    score: cand.score
                )
            }
            cacheLock.lock()
            lastHistoryKey = Romanization.aliasReading(displayBuffer)
            cacheLock.unlock()
            return state
        }
        // Composing punctuation (`.`, `:`, `*`, `'`) can appear inside
        // the roman run even when it cannot be consumed by a vowel or
        // connector rule. Split those literal runs before the parser can
        // skip them and silently erase what the user typed.
        if let split = splitAtLastEmbeddedComposingPunct(displayBuffer) {
            var state = updateInternal(buffer: split.activeBuffer, context: context)
            state.rawBuffer = displayBuffer
            // TASK-032: when the active buffer composes to a Burmese
            // surface (no residual ASCII letters in rank-0), the
            // split-position `:`/`.` is unambiguously a Burmese tone
            // marker on the preceding bare-`<C>a` / medial-bearing /
            // asat-coda syllable rather than mid-buffer ASCII
            // punctuation. Re-render the prefix with the trailing
            // tone absorbed onto the preceding Myanmar syllable.
            //
            // The activeBufferIsBurmeseComposable check looks at the
            // top inner candidate: when its surface contains no
            // ASCII letters, the tail is fully Burmese-composable and
            // tone absorption is the right rank-0 outcome.
            //
            // The trailingPunct check reads the original buffer slice
            // (not split.renderedPrefix) because Burmese-punctuation
            // mapping may have already replaced the `.`/`:` with
            // U+104A/U+104B in the rendered prefix.
            let prefixSliceLen = displayBuffer.count - split.activeBuffer.count
            let prefixSlice = String(displayBuffer.prefix(prefixSliceLen))
            let activeBufferIsBurmeseComposable: Bool = {
                guard let top = state.candidates.first else { return false }
                let trailingPunct = prefixSlice.last
                guard trailingPunct == ":" || trailingPunct == "." else { return false }
                return !top.surface.unicodeScalars.contains {
                    let v = $0.value
                    return (v >= 0x41 && v <= 0x5A) || (v >= 0x61 && v <= 0x7A)
                }
            }()
            let effectivePrefix: String
            if activeBufferIsBurmeseComposable {
                effectivePrefix = renderFrozenPunctSegments(
                    prefixSlice,
                    absorbTrailingToneIfBurmeseFollows: true
                )
            } else {
                effectivePrefix = split.renderedPrefix
            }
            if state.candidates.isEmpty {
                state.candidates = [Candidate(
                    surface: effectivePrefix + split.activeBuffer,
                    reading: displayBuffer,
                    source: .grammar,
                    score: 0
                )]
            } else {
                state.candidates = state.candidates.map { cand in
                    Candidate(
                        surface: effectivePrefix + cand.surface,
                        reading: displayBuffer,
                        source: cand.source,
                        score: cand.score
                    )
                }
            }
            // The inner update set lastHistoryKey to the active suffix's
            // alias (e.g. `la` for `ka.la`) — overwriting it here with
            // the full-buffer alias keeps `recordSelection` from
            // writing a truncated key that pollutes future short-prefix
            // lookups. See task 05.
            cacheLock.lock()
            lastHistoryKey = Romanization.aliasReading(displayBuffer)
            cacheLock.unlock()
            return state
        }
        // Mid-buffer literal punctuation (task 03): when ANY non-composable
        // non-digit character (e.g. `,`, `;`, `-`, `_`, `(`, `)`, `!`, `?`,
        // mapped subset `.`, `,`, `!`, `?`, `;`) sits between two composable
        // runs, split the buffer at the *last* such literal-punct and
        // recurse on the active suffix so it is parsed as Myanmar instead
        // of held verbatim in the literal tail. Mapped punct is substituted
        // for its Myanmar equivalent only when `burmesePunctuationEnabled`
        // is on; non-mapped literal punct stays verbatim regardless. This
        // generalises the older `splitAtLastEmbeddedMappedPunct` path
        // (which only fired for the five mapped chars under the toggle).
        if let split = splitAtLastEmbeddedLiteralPunct(displayBuffer) {
            var state = updateInternal(buffer: split.activeBuffer, context: context)
            state.rawBuffer = displayBuffer
            if state.candidates.isEmpty {
                // Active portion produced nothing parseable; surface the
                // frozen prefix + raw active so the user still sees the
                // settled portion and doesn't lose their composition.
                state.candidates = [Candidate(
                    surface: split.renderedPrefix + split.activeBuffer,
                    reading: displayBuffer,
                    source: .grammar,
                    score: 0
                )]
            } else {
                state.candidates = state.candidates.map { cand in
                    Candidate(
                        surface: split.renderedPrefix + cand.surface,
                        reading: displayBuffer,
                        source: cand.source,
                        score: cand.score
                    )
                }
            }
            // See the matching block above — the inner update keyed
            // lastHistoryKey on the active suffix; we restore the
            // full-buffer alias here so commits don't pollute the
            // history table with truncated keys (task 05).
            cacheLock.lock()
            lastHistoryKey = Romanization.aliasReading(displayBuffer)
            cacheLock.unlock()
            return state
        }
        // Peel a leading literal head (punctuation, brackets, quotes, …)
        // before digits / composable extraction. Without this, a buffer
        // starting with e.g. `.` or `(` collapses the composable prefix to
        // empty and returns no candidates even though `aung` / `thar`
        // after the literal are perfectly parseable.
        let (leadingLiteral, postLeadingLiteralBuffer) =
            Self.splitLeadingLiteral(displayBuffer)
        // Strip leading ASCII digits — they convert directly to Myanmar
        // digits and are prepended to candidate surfaces after the
        // composable portion is parsed.
        //
        // TASK-052: when digits are present at the head, also peel any
        // immediately-following `*` (asat-marker) chars and any further
        // interleaved digit runs into the prefix. The asat marker
        // requires a consonant base on its left to anchor the U+103A
        // scalar — digits never serve as that base. Letting `*` reach
        // the parser in this position produces a `200C 103A` orphan
        // that the orphan-mark sanitizer then anchors to a phantom
        // U+1021 (`အ`), surfacing the malformed `<digit> 1021 103A`
        // cluster (`1*` → `၁အ်`). Folding the `*` chars into the
        // digit-prefix run treats them as literal pass-throughs:
        // `1*` → `၁*`, `1*ka` → `၁*က`, `12*34` → `၁၂*၃၄`.
        let (digitPrefix, postDigitBuffer) =
            Self.splitLeadingDigitsAndAdjacentAsterisks(postLeadingLiteralBuffer)
        // Candidates are generated only from the leading run of composing
        // characters. Anything after the first non-composing character
        // (punctuation, whitespace, etc.) is held aside and emitted verbatim
        // on commit — this lets the user freely mix Burmese-convertible text
        // with literal content without the IME swallowing either.
        let (rawComposable0, rawLiteralTail) = splitComposablePrefix(postDigitBuffer)
        // Trailing `'` characters surface as literal quote/apostrophe marks,
        // not as null-vowel connectors. Peel them into the literal tail before
        // the composable run reaches the parser (task 03).
        var rawComposable = rawComposable0
        var trailingApostrophes = ""
        while rawComposable.last == "'" {
            rawComposable.removeLast()
            trailingApostrophes = "'" + trailingApostrophes
        }
        // `.` is in `Romanization.composingCharacters` for abbreviation
        // handling, so trailing punctuation lands in the composable portion
        // rather than the literal tail. When punctuation mapping is on,
        // peel those trailing mapped chars off so the parser doesn't try
        // to consume them — they rejoin the tail below and get substituted
        // with their Myanmar equivalent when the surface is assembled.
        let composable: String
        let literalTail: String
        if burmesePunctuationEnabled {
            let (kept, peeled) = stripTrailingMappablePunctuation(rawComposable)
            composable = kept
            literalTail = peeled + trailingApostrophes + rawLiteralTail
        } else {
            composable = rawComposable
            literalTail = trailingApostrophes + rawLiteralTail
        }
        let initialNormalized = Self.normalizeForParser(composable)
        guard !initialNormalized.isEmpty else {
            // No composable text: if digits or literal text are present,
            // offer Burmese and Arabic digit candidates directly.
            return digitOrLiteralFallback(
                leadingLiteral: leadingLiteral,
                digitPrefix: digitPrefix,
                literalTail: literalTail,
                displayBuffer: displayBuffer,
                context: context
            )
        }

        // Shrink from the right until the parser produces a fully legal
        // parse that doesn't begin with a standalone tall-aa vowel (ar2,
        // aw2, out2, aung2). The dropped suffix joins `literalTail`, so
        // "min:123" emits မင်း + "123" and "ar2" emits ာ + "2" — the
        // tall-aa variant remains reachable only when a descender onset is
        // actually present in the buffer.
        //
        // The probe always runs on the full normalized buffer: probing
        // only a trailing slice would start mid-syllable for long inputs
        // and reject valid letters that parse fine in full context.
        //
        // `parseLongestAcceptablePrefix` collapses the per-length loop
        // into a single DP pass + backward walk of its buckets. On garbage
        // / keyboard-bashing input this turns O(n) full parses into O(1).
        // TASK-027: peel a trailing run of `y`/`w`/`r`/`l` letters off
        // the buffer when they are the doubled-coda artifact (`kayy`,
        // `kall`, `kawww`, `karrr`) or the stray-coda after a long
        // closed-syllable vowel rule (`myaungy`). The peeled letters
        // are kept in `peeledTrailingCoda` and discarded entirely from
        // the composing pipeline — the parser must not see them
        // (otherwise it would re-pick the visible-standalone-consonant
        // chain that produces the bug surface), and the literal-tail
        // composer must not re-render them either. The user still sees
        // their original keystrokes via the engine's composing buffer
        // overlay; the panel surface drops the artifact.
        //
        // TASK-026 follow-up: peel a doubled bare-vowel tail (`ee`,
        // `ii`, `oo`, `uu`) when it is followed by a tone marker
        // (`kee.`, `kii:`, `koo.`, `kuu:`). Without this pre-pass the
        // tone marker consumes the trailing position so the right-
        // shrink probe never drops the duplicate vowel into
        // `droppedTail`, leaving `trimChainedBareVowelTail` unable to
        // fire and the malformed double-anchor surfaces re-emerge
        // (`ကယ်ယ့်`, `ကီည့်`, `ကိုအို့`, `ကူဥ`). The peel runs before
        // `peelRepeatedTrailingCoda` so the tone-marker re-attach
        // chains correctly across both guards.
        let preToneTrimmedNormalized =
            Self.peelDoubledBareVowelTrailingTone(initialNormalized)
        // TASK-039: collapse a leading `ee*` doubled-bare-vowel run
        // when the buffer continues with non-`e` content. The
        // doubled-`e` chain produces an illegal `1021 101A 103A
        // 101A 103A` doubled-ya-asat coda surface that never
        // corresponds to real Burmese spelling.
        let leadingEeTrimmed =
            Self.peelLeadingDoubledE(preToneTrimmedNormalized)
        let (preTrimmedNormalized, peeledTrailingCoda) =
            Self.peelRepeatedTrailingCoda(leadingEeTrimmed)
        let (acceptableLen, _) = parser.parseLongestAcceptablePrefix(
            preTrimmedNormalized,
            maxResults: 1,
            acceptable: Self.isAcceptableParse
        )
        let initialChars = Array(preTrimmedNormalized)
        let normalizedInitial = String(initialChars.prefix(acceptableLen))
        let droppedTailInitial = String(initialChars.suffix(initialChars.count - acceptableLen))
        _ = peeledTrailingCoda  // dropped from the composing pipeline

        // TASK-026: trim a doubled-bare-vowel tail run from the dropped
        // section when its leading characters match the kept buffer's
        // last character. The DP guard
        // (`Parser/NBestDP.swift::runDP`) rejects chained `vowelOnly`
        // arcs after a paired consonant + bare-vowel arc for the
        // bare-vowel keys `i`/`u`/`e`/`o`, so the right-shrink probe
        // peels the duplicated letters off into `droppedTail`. Without
        // this trim the tail composer re-renders them as a second
        // visible syllable that, when concatenated to the kept prefix,
        // produces the exact scalar shapes the task forbids
        // (`<C>ိုအို` / `<C>ယ်ယ်` for the `o` and `e` rules whose
        // surfaces don't carry an orphan-ZWNJ promotable to a clean
        // `1021` separator).
        let (normalized, droppedTail) = Self.trimChainedBareVowelTail(
            normalized: normalizedInitial,
            droppedTail: droppedTailInitial
        )

        guard !normalized.isEmpty else {
            // Right-shrink probe consumed the entire composable run as
            // unparseable (e.g. lone `.` / `:` after a digit prefix).
            // Route through the same digit/literal fallback the
            // empty-`initialNormalized` branch uses so a `<digits><.|:>`
            // buffer still emits Myanmar-digit + ASCII-digit candidates
            // instead of an empty panel (TASK-003). The dropped tail
            // joins the literal tail since neither portion contributed
            // to a valid Myanmar parse.
            return digitOrLiteralFallback(
                leadingLiteral: leadingLiteral,
                digitPrefix: digitPrefix,
                literalTail: droppedTail + literalTail,
                displayBuffer: displayBuffer,
                context: context
            )
        }

        let rawEffectiveTail = droppedTail + literalTail
        // Punctuation auto-mapping substitutes Myanmar ။/၊ inside the tail
        // so the trailing char appears as part of each candidate surface
        // instead of forcing an early commit. Mapping touches only the
        // exact five ASCII punctuation chars — letters the parser dropped
        // into `droppedTail` pass through unchanged.
        let mappedEffectiveTail = burmesePunctuationEnabled
            ? Self.mapPunctuation(rawEffectiveTail)
            : rawEffectiveTail
        // When the right-shrink probe drops composing characters, re-run
        // the tail through the single-best fallback composer before it is
        // concatenated onto every surface. Literal tails that started after
        // a non-composing boundary still pass through unchanged.
        let effectiveTail: String
        let droppedTailHasComposingChars = droppedTail.contains {
            Romanization.composingCharacters.contains($0)
        }
        let droppedTailHasComposingPunctuation = droppedTail.contains {
            $0 == "+" || $0 == "*" || $0 == "'" || $0 == ":" || $0 == "."
        }
        let droppedTailHasAsciiLetters = droppedTail.unicodeScalars.contains {
            $0.value >= 0x61 && $0.value <= 0x7A
        }
        // TASK-018: when the right-shrink probe peels a long
        // inherent-A chain (`kaaaaakaa` → kept `k`, dropped
        // `aaaaakaa`), the resulting dropped tail starts with three
        // or more `a`s. Without this allowance the 6-character gate
        // strands the tail as raw ASCII at rank 0, which contradicts
        // the engine's Roman-only Myanmar pipeline contract.
        // Restricted to the `a{3,}<rest>` shape so arbitrary
        // long-letter-only buffers (`ureqnborylahzy`-style fuzz
        // inputs) keep their existing literal-tail behaviour and the
        // parser-internal re-segmentation of the dropped tail does
        // not break anchor monotonicity for unrelated inputs.
        let droppedTailIsLongInherentAChain = droppedTailHasInherentAChainPrefix(droppedTail)
        let shouldComposeDroppedTail = !droppedTail.isEmpty
            && droppedTailHasComposingChars
            && (droppedTail.count <= 6
                || droppedTailHasComposingPunctuation
                || droppedTailIsLongInherentAChain)
        if tailStartsWithDigit(literalTail, dropped: droppedTail)
            || shouldComposeDroppedTail {
            effectiveTail = composeLetterRunsInTail(mappedEffectiveTail)
        } else {
            effectiveTail = mappedEffectiveTail
        }

        // Prefix-stability anchor: when the new buffer extends a
        // previously-rendered one *and* that anchor is mature enough
        // (`anchor.normalized.count >= anchorCommitThreshold`), reuse
        // the anchor surface verbatim and only re-parse the tail. Mature
        // anchors are treated as committed so the already-visible
        // rendering cannot drift. Below the threshold the anchor is
        // tentative — we perform a fresh full-buffer parse instead, so
        // early ambiguous picks get overwritten once evidence accrues.
        cacheLock.lock()
        let historySnapshot = anchorHistory
        cacheLock.unlock()
        // Walk the history deepest → shallowest and pick the first anchor
        // whose (a) normalized is a strict prefix of the current buffer,
        // (b) is long enough to count as committed, and (c) whose tail
        // parses on its own. A mature anchor whose tail cannot parse
        // (e.g. single trailing "a" or ":") would otherwise zero out the
        // candidate panel or force a full-buffer fallback that drifts;
        // stepping back to a shallower checkpoint gives us a parseable
        // tail while still preserving all prior committed text.
        // Minimum tail length for anchor-based windowing. A very short
        // tail (e.g. 1-2 chars) always "parses" as a bare consonant, but
        // that greedily locks in the anchor boundary and prevents multi-
        // character onsets (like "th" → သ) from forming across it. The
        // tail must be long enough for the parser to see the full onset +
        // vowel at the boundary; `maxOnsetLen` is the safe minimum.
        let minAnchorTailLen = parser.maxOnsetLen
        let priorAnchor: PrefixAnchor? = {
            guard normalized.count > compositionWindowSize else { return nil }
            let normalizedCharsForAnchors = Array(normalized)
            for anchor in historySnapshot.reversed() {
                guard !anchor.normalized.isEmpty,
                      normalized.hasPrefix(anchor.normalized),
                      normalized.count > anchor.normalized.count,
                      anchor.normalized.count >= anchorCommitThreshold,
                      !Self.isUnsafeFrozenSplit(
                          chars: normalizedCharsForAnchors,
                          split: anchor.normalized.count
                      )
                else { continue }
                let tail = String(normalized.suffix(normalized.count - anchor.normalized.count))
                guard tail.count >= minAnchorTailLen else { continue }
                let probe = cachedGrammarParses(tail, maxResults: 1, isFullBuffer: true)
                if probe.contains(where: { Self.isAcceptableParse($0) }) {
                    return anchor
                }
            }
            return nil
        }()
        // Suppress anchor-windowing when the full normalized buffer has an
        // exact-alias lexicon entry: a curated multi-word lexicon hit like
        // "မင်္ဂလာပါ" deserves to win over a synthesized prefix + tail
        // rendering. Anchor-windowing is still correct for novel inputs
        // where no full-buffer lexicon entry exists (the kwyantawkahtamin
        // case), because there the lookup is empty and this guard is false.
        let preAliasPrefix = Romanization.aliasReading(normalized)
        let preComposeKey = Romanization.composeLookupKey(normalized)
        let hasExactLexiconMatch: Bool = {
            let hits = candidateStore.lookup(prefix: preAliasPrefix, previousSurface: context.last)
            return hits.contains {
                Romanization.aliasReading($0.reading) == preAliasPrefix
                    || Romanization.composeLookupKey($0.reading) == preComposeKey
            }
        }()
        // Only use anchor-based parse splitting for long buffers where the
        // sliding window is needed. For short buffers (below compositionWindowSize),
        // always do a full-buffer parse so that syllable boundaries can be
        // freely revised as new characters arrive. Without this gate, the anchor
        // greedily commits boundaries that later keystrokes should change —
        // e.g. "la" + "r" staying as လ+ရ instead of becoming လာ (l + ar vowel),
        // or "ka" + "h" staying as က+ဟ instead of becoming က+ထ (ka + ht onset).
        let anchorApplies = priorAnchor != nil
            && !hasExactLexiconMatch
            && normalized.count > compositionWindowSize

        let prefixBranches: [FrozenPrefixBranch]
        let parseInput: String
        let windowed: Bool
        var lmCache: [LMScoreKey: Double] = [:]
        if anchorApplies, let anchor = priorAnchor {
            let anchorLM = scoreSurfaceCached(anchor.surface, context: context, cache: &lmCache)
            prefixBranches = [FrozenPrefixBranch(
                output: anchor.surface,
                reading: anchor.reading,
                lmScore: anchorLM,
                contextWords: context + [anchor.surface]
            )]
            parseInput = String(normalized.suffix(normalized.count - anchor.normalized.count))
            windowed = true
        } else if normalized.count > compositionWindowSize {
            // Prefer reusing a previously chosen frozen prefix so the
            // "committed" portion the user sees doesn't shift as they
            // type. The cached prefix is reused verbatim when it is
            // still a prefix of the current buffer and the remaining
            // tail hasn't grown past `maxActiveTailSize`. Only when the
            // tail exceeds that budget do we extend the split forward —
            // the new split is constrained to land at or after the
            // cached endpoint, so the committed portion only grows.
            let cachedLen = stableCachedPrefixLength(for: normalized)
            let normalizedChars = Array(normalized)
            let cachedIsUnsafe = cachedLen.map {
                Self.isUnsafeFrozenSplit(chars: normalizedChars, split: $0)
            } ?? false
            let split: Int
            if let cached = cachedLen,
               !cachedIsUnsafe,
               normalized.count - cached <= Self.maxActiveTailSize {
                split = cached
            } else {
                let splitLowerBound = max(cachedLen ?? 0, anchorCommitThreshold)
                split = cachedFindSyllableSafeSplit(
                    in: normalized,
                    targetTail: compositionWindowSize,
                    lowerBound: splitLowerBound
                )
            }
            let frozenPrefix = String(normalized.prefix(split))
            let activeTail = String(normalized.suffix(normalized.count - split))
            prefixBranches = renderFrozenPrefixBranches(frozenPrefix, baseContext: context, lmCache: &lmCache)
            parseInput = activeTail
            windowed = true
        } else {
            prefixBranches = []
            parseInput = normalized
            windowed = false
        }

        // When windowed, the tail-only input occasionally can't parse as
        // a standalone syllable (e.g. "ka" has no onset-less "a" rule in
        // this romanization). Falling through to an empty candidate pool
        // would blank the panel mid-word. Detect that case and retry
        // with the full normalized buffer so the user still sees
        // candidates — we trade a per-keystroke re-parse of the prefix
        // for continuity of the panel.
        var effectiveParseInput = parseInput
        var effectivePrefixBranches = prefixBranches
        var effectiveWindowed = windowed
        var grammarParses = cachedGrammarParses(
            effectiveParseInput,
            maxResults: Self.grammarCandidateBudget(for: effectiveParseInput),
            isFullBuffer: !effectiveWindowed
        )
        grammarParses.removeAll { Self.hasInterleavedLatin($0.output) }
        // Ya-pin disambiguator alt-parse: when the buffer starts with one
        // of `yaPinPreferredOnsetClusters` (`khwy`/`ghwy`/`kwy`/`gwy`/
        // `khy`/`ghy`/`ky`/`gy`), re-parse with the digit-suffixed form
        // (`kwy2…`, `ky2…`) and merge the resulting parses. The DP's
        // aliasCost-first ordering would otherwise prune the ya-pin
        // sibling out of the N-best beam once enough syllables stack
        // up — leaving `promoteYapinForExactBareReading` nothing to
        // promote. Forcing the ya-pin path through a parallel parse
        // restores the symmetric candidate pool that the short-buffer
        // promotion (TASK-058) was designed to operate on.
        if let disambiguated = Self.yaPinDisambiguatedInput(effectiveParseInput) {
            let disambiguatedParses = parser.parseCandidates(
                disambiguated,
                maxResults: Self.grammarCandidateBudget(for: effectiveParseInput),
                isFullBuffer: !effectiveWindowed
            )
            let existingOutputs = Set(grammarParses.map(\.output))
            for parse in disambiguatedParses
            where !Self.hasInterleavedLatin(parse.output)
               && !existingOutputs.contains(parse.output) {
                grammarParses.append(parse)
            }
        }
        // Parser-level orphan promotion (task 01): generate implicit-အ
        // siblings for parses whose surface has an unanchored mark. The
        // leading-ZWNJ case swaps the ZWNJ for အ; the mid-surface case
        // inserts အ before every interior orphan
        // (`<...>103A 102D<...>` and friends). Both can coexist on the
        // same parent (`aungain` surfaces as ZWNJ + ...103A 102D...), so
        // run the mid-surface pass on the ZWNJ-promoted sibling too.
        // `sanitizeMalformedMyanmarMarks` drops the original orphan once
        // a legal sibling survives.
        let originalGrammarParseCount = grammarParses.count
        for i in 0..<originalGrammarParseCount {
            let parent = grammarParses[i]
            let zwnjPromoted = Self.promoteOrphanZwnjToImplicitA(parent)
            if let zwnjPromoted {
                grammarParses.append(zwnjPromoted)
            }
            if let promoted = Self.promoteOrphanInternalMarks(parent) {
                grammarParses.append(promoted)
            }
            if let zwnjPromoted,
               let promoted = Self.promoteOrphanInternalMarks(zwnjPromoted) {
                grammarParses.append(promoted)
            }
        }
        // Explicit user-typed `+` (task 01): when the buffer carries an
        // explicit `+`, the primary strict parse rejects cross-class
        // pairs (`pad+ma`, `brah+ma`, `nag+ma`) and the DP soft-boundary
        // path silently drops the virama. Re-parse with liberal stack
        // validation so the cross-class stacked surface reaches the
        // candidate pool. The user explicitly asked for a stack — so the
        // liberal merge does NOT pay the rarity penalty that the
        // implicit-inference path applies to demote liberal stacks on
        // plain Burmese compounds. Same-class pairs (`pak+ka`, `dham+ma`)
        // are unaffected: strict and liberal both produce the same
        // surface, and the dedupe-by-output skips the duplicate.
        if effectiveParseInput.contains("+") {
            let liberalParses = parser.parseCandidates(
                effectiveParseInput,
                maxResults: Self.grammarCandidateBudget(for: effectiveParseInput),
                isFullBuffer: !effectiveWindowed,
                allowLiberalStacks: true
            )
            let existingOutputs = Set(grammarParses.map(\.output))
            for parse in liberalParses
            where !Self.hasInterleavedLatin(parse.output)
               && !existingOutputs.contains(parse.output) {
                grammarParses.append(parse)
            }
        }
        // Stack inference (tasks 09/05): when the buffer carries no
        // explicit `+` but has an orthographic kinzi / Pali virama-stack
        // site (`<V><coda><C>`), re-parse with the inferred `+` injected
        // and merge the resulting parses so the stacked surface enters the
        // ranking pool alongside the unstacked one. The inference pass uses
        // liberal stack validation; regular parsing remains strict.
        //
        // Each injected `+` materialises as a DP vowelOnly transition
        // that bumps `syllableCount` by 1 even when the site resolves
        // to a stack — so the stacked parse would lose the
        // `syllableCount` tiebreaker against the shorter unstacked
        // parse of the same buffer. Decrement the inferred parse's
        // `syllableCount` by the number of injected `+`s so the count
        // reflects what the user perceives (a stacked compound is one
        // syllable, not two).
        // Skip stack inference when the lexicon already holds the exact
        // buffer — the curated form carries source=.lexicon, and a
        // parallel grammar parse with the same surface would steal the
        // lexicon source when the merge dedupes by surface. The
        // lexicon result is strictly better than anything inference
        // could add here, so bow out.
        var strictInferredStackOutputs: Set<String> = []
        // Liberal-inferred kinzi surfaces from the diphthong-coda bare-ng
        // collapse (task 04). These carry a rarity bump so the open form
        // wins at rank 0, but they must survive LM pruning so the kinzi
        // sibling is reachable in the panel at rank ≥ 1. They are kept
        // separate from `strictInferredStackOutputs` so the rank-0
        // promotion block (bestStrictInferredStackIndex) does not fire on
        // them.
        var liberalKinziOutputs: Set<String> = []
        // Digit boundaries only apply to the full (non-windowed) cleaned
        // buffer. When windowed, the active tail has different offsets.
        let inferBoundaries = effectiveWindowed ? [] : midDigitBoundaries
        if !hasExactLexiconMatch,
           let inferred = Self.inferImplicitStackMarkers(
               effectiveParseInput,
               digitBoundaries: inferBoundaries
           ) {
            let existingOutputs = Set(grammarParses.map(\.output))
            // Add parses for the full inferred input (every `+` site).
            ingestInferredParses(
                input: inferred.input,
                insertions: inferred.insertions,
                liberalInsertions: inferred.liberalInsertions,
                vowelRuleLiberalInsertions: inferred.vowelRuleLiberalInsertions,
                isFullBuffer: !effectiveWindowed,
                grammarParses: &grammarParses,
                existingOutputs: existingOutputs,
                strictInferredStackOutputs: &strictInferredStackOutputs,
                liberalKinziOutputs: &liberalKinziOutputs
            )
            // When the buffer mixes strict-valid (e.g. kinzi) and
            // liberal-only (cross-class Pali) inference sites, also
            // add parses for the strict-only inferred input. This
            // gives the ranker a clean kinzi/native-stack candidate
            // that doesn't carry the liberal cross-class virama
            // (task 04: prevent liberal sites from poisoning the
            // strict parse via shared structure/syllable scoring).
            if let strictOnly = inferred.strictOnlyInput {
                let outputsAfterFull = Set(grammarParses.map(\.output))
                ingestInferredParses(
                    input: strictOnly,
                    insertions: inferred.strictOnlyInsertions,
                    liberalInsertions: 0,
                    vowelRuleLiberalInsertions: 0,
                    isFullBuffer: !effectiveWindowed,
                    grammarParses: &grammarParses,
                    existingOutputs: outputsAfterFull,
                    strictInferredStackOutputs: &strictInferredStackOutputs,
                    liberalKinziOutputs: &liberalKinziOutputs
                )
            }
            // TASK-006: when bug-class N+T sites coexist with promotable
            // sites (kinzi / native virama-stack), inject a sibling
            // parse that carries ONLY the promotable `+`s. The parser
            // surface for this sibling has the kinzi (e.g. `သင်္ဂြ`)
            // without the cross-class virama (`န္တ`), so the engine's
            // rank-0 promotion of `strictInferredStackOutputs` lifts
            // the kinzi-bearing surface even though the full-stack
            // sibling is demoted by the bug-class rarity bump.
            if let promotableOnly = inferred.promotableOnlyInput {
                let outputsAfterStrict = Set(grammarParses.map(\.output))
                ingestInferredParses(
                    input: promotableOnly,
                    insertions: inferred.promotableOnlyInsertions,
                    liberalInsertions: 0,
                    vowelRuleLiberalInsertions: 0,
                    isFullBuffer: !effectiveWindowed,
                    grammarParses: &grammarParses,
                    existingOutputs: outputsAfterStrict,
                    strictInferredStackOutputs: &strictInferredStackOutputs,
                    liberalKinziOutputs: &liberalKinziOutputs
                )
            }
            // Inferred parses arrive after the orphan-ZWNJ promotion
            // pass above, so any inferred surface that materialises a
            // leading ZWNJ + combining mark (the standard parser
            // emission for an onset-less leading vowel rule) misses
            // the promotion and gets filtered by `sanitizeOrphanZwnj`
            // downstream. Run a second promotion pass on the
            // inferred parses, but ONLY when the buffer is the
            // diphthong-collapse fast-path shape (`ai + ng +
            // <stackable>`, task 04) — that is the only inference
            // path whose user-intended surface is a kinzi-anchored
            // form like `အိုင်္ဂါ` that requires the
            // ZWNJ→အ promotion to survive sanitisation. Other
            // inference paths (existing inference at boundaries
            // inside the buffer, generic `*+` injections) already
            // produce surfaces that either ride forward via the
            // primary parses' promoted siblings or are not the
            // user's intended top — promoting them would surface
            // spurious kinzi candidates for inputs like `aing` or
            // `aingthi`.
            // Match the exact fast-path signature in
            // `inferImplicitStackMarkers`: buffer starts with `aing`
            // and the next character forms a strict-valid kinzi pair
            // with `nga` (velar-class lower like `g`, `k`, `kh`,
            // `gh`). For other `aing<X>` shapes the inferred kinzi
            // is a spurious nga+nga interpretation that should not
            // surface as the user-visible top.
            let isAiNgFastPathShape: Bool = {
                let bufChars = Array(effectiveParseInput)
                guard bufChars.count >= 5,
                      bufChars[0] == "a", bufChars[1] == "i",
                      bufChars[2] == "n", bufChars[3] == "g"
                else { return false }
                let lowers = Self.stackLowerConsonantsStarting(chars: bufChars, at: 4)
                return lowers.contains { Grammar.isValidStack(upper: Myanmar.nga, lower: $0) }
            }()
            // Onsetless leading-vowel + Pali-stack site (TASK-010): when
            // the buffer starts with an independent-vowel romanization
            // key (`o`, `aw`, `oo`, …) and the inferred parse produces
            // a leading ZWNJ + dependent-vowel surface (parser's bare-
            // vowel emission), promote ZWNJ→U+1021 so the inferred
            // candidate's surface matches the merged-candidate form
            // and `strictInferredStackOutputs` tracks the legal anchor
            // shape. Without this, the inferred stacked candidate
            // (`အိုက္က` for `okka`) never enters the rank-0 promotion
            // set and the no-`+` flat sibling wins.
            //
            // The promotion is gated to consonant-upper virama stacks
            // (no asat between the consonant and the virama) — the
            // diphthong-kinzi family (`ainga`, `kar:aing`) materialises
            // an `<asat> 1039 <consonant>` shape that
            // `surfaceHasOnlyNativeViramaStacks` accepts as legal but
            // is structurally a *vowel-rule-derived* kinzi, not a
            // Pali stack on a leading bare vowel. Promoting those
            // would lift the kinzi candidate above the open form for
            // inputs like `ainga` (TASK-006 carve-out).
            let isLeadingBareVowelStackShape: Bool = {
                // Windowed buffers are excluded — the active tail may
                // start with an arbitrary vowel even though the user-
                // visible buffer doesn't, and the prefix-cache anchor
                // monotonicity invariant is sensitive to incremental
                // promotion choices. The bug class targets short
                // self-contained buffers (`okka`, `ekka`, `aykka`, …)
                // which never window in practice.
                guard !effectiveWindowed else { return false }
                // The bug class is "buffer is a short Pali word that
                // begins with a bare vowel." Long buffers that happen
                // to start with a vowel may pull in spurious kinzi
                // promotions through the diphthong-coda paths
                // (`ainga`, `kar:aing`, …) which the existing
                // `isAiNgFastPathShape` already handles. Cap at 8
                // chars — every reproduction in TASK-010 fits within
                // 6 chars (`ekka`, `aykka`, `iddha`, `enta`, …).
                guard effectiveParseInput.count <= 8 else { return false }
                guard let firstChar = effectiveParseInput.first else { return false }
                let vowelLeaders: Set<Character> = ["a", "e", "i", "o", "u"]
                return vowelLeaders.contains(firstChar)
            }()
            if isAiNgFastPathShape || isLeadingBareVowelStackShape {
                let inferredCount = grammarParses.count
                for i in 0..<inferredCount {
                    let parent = grammarParses[i]
                    if let zwnjPromoted = Self.promoteOrphanZwnjToImplicitA(parent),
                       !grammarParses.contains(where: { $0.output == zwnjPromoted.output }) {
                        grammarParses.append(zwnjPromoted)
                        if Self.surfaceHasOnlyNativeViramaStacks(zwnjPromoted.output) {
                            // Only register as a strict-inferred-stack
                            // surface (which triggers rank-0 promotion)
                            // when this is a Pali-style consonant stack
                            // — not the diphthong-kinzi shape that
                            // `aing<X>` patterns produce. The aing
                            // fast-path keeps its own promotion via
                            // `isAiNgFastPathShape`.
                            let isPaliConsonantStack = isAiNgFastPathShape
                                || Self.surfaceHasConsonantOnlyViramaStack(zwnjPromoted.output)
                            if isPaliConsonantStack {
                                strictInferredStackOutputs.insert(zwnjPromoted.output)
                                strictInferredStackOutputs.insert(Self.correctAaShape(zwnjPromoted.output))
                            }
                        }
                    }
                }
            }
        }
        // TASK-031: Explicit user-typed `+` strict-stack promotion.
        // When the user typed `+`s in the buffer, the parser respects
        // them as soft boundaries and produces the kinzi / native-
        // virama-stack / na-asat-closure surface at parser top-1
        // (e.g. `min+ga` → `မင်္ဂ`, `kan+ga` → `ကန်ဂ`,
        // `yan+gun` → `ယန်ဂူန`, `nan+ga` → `နန်ဂ`). Without this
        // block the engine's LM-driven composite ranking can re-rank
        // an alternative segmentation above the user-respecting
        // surface — concretely `min+ga` displaces to `မည်န္ဂ` (a
        // `mi2na+ga`-reading parse that introduces a virama where
        // the user wanted kinzi), and `kan+ga` displaces to `ကံဂ`
        // (anusvara closure instead of na+asat). The user-typed `+`
        // is the strongest possible "stack here" signal, so route
        // every parse whose reading exactly matches the user's
        // literal input through the existing
        // `bestStrictInferredStackIndex` rank-0 lift.
        //
        // Discriminator: parse.reading == effectiveParseInput, OR
        // parse.reading == effectiveParseInput + "a". The parser's
        // reading carries internal disambiguators like `2`/`3`
        // (retroflex / anusvara variants) when it picked a
        // non-literal segmentation; a literal-match means the parse
        // preserved the user's exact keystrokes and `+` placement.
        // The "+a" sibling matches the parser's normal habit of
        // appending the inherent vowel `a` after a trailing bare
        // consonant — `yan+gun` → reading `yan+guna`, `thin+kun` →
        // reading `thin+kuna`, etc. — so the user-respecting parse
        // for a `<...>n+<lower>n` shape still surfaces. Variant
        // parses (`kan2+ga`, `yan+gu2na`, `yan+gun2a`, `yan3+guna`,
        // …) stay in the panel at lower rank: they're not promoted
        // here, but the user can still pick them via the panel.
        if !effectiveWindowed && displayBuffer.contains("+") {
            // Compare against the user's pre-reshape `displayBuffer`
            // rather than `effectiveParseInput`. The
            // `collapseConnectorRuns` TASK-011 reshape strips an
            // upper's inherent `a` before `+` (e.g. `thin+ga+thin`
            // → `thin+g+thin`) before the parser sees the buffer;
            // the parser's reading rebuilds that `a` so reading
            // matches the user's original keystrokes again. A
            // displaced parse (e.g. `mina+ga` for user `min+ga`)
            // produces a reading that does NOT match the user's
            // typed buffer, so the discriminator correctly excludes
            // it. The trailing-`a` allowance covers the parser's
            // habit of appending an inherent vowel after a bare
            // trailing consonant (`yan+gun` → reading `yan+guna`).
            //
            // TASK-053: when the user typed a trailing tone marker
            // (`.`/`:`) or digit, the right-shrink probe peels it
            // into the literal tail and `effectiveParseInput`
            // doesn't carry it; the parser's reading on the
            // shrunk input also doesn't carry it. To still match
            // these tone-suffixed kinzi/asat-closure parses, try
            // both the verbatim `displayBuffer` and a
            // tone-/digit-stripped sibling. The original display
            // buffer covers parses whose reading already carries
            // the tone (`than+gar.` → reading `thana+gar.`); the
            // stripped sibling covers parses on the right-shrunk
            // tail (`min+ga.` → parser saw `min+ga`, reading
            // `min+ga`).
            let userLiteralStripped = Self.stripTrailingToneAndDigitMarkers(displayBuffer)
            for parse in grammarParses
            where Self.readingMatchesUserLiteralAcrossInherentVowels(
                    parseReading: parse.reading,
                    userInput: displayBuffer
                ) || (userLiteralStripped != displayBuffer
                    && Self.readingMatchesUserLiteralAcrossInherentVowels(
                        parseReading: parse.reading,
                        userInput: userLiteralStripped
                    )) {
                strictInferredStackOutputs.insert(parse.output)
                strictInferredStackOutputs.insert(Self.correctAaShape(parse.output))
            }
        }
        // `windowFallback` is set when the tail-only parse failed so we
        // retried with the full buffer. In that case the anchor is still
        // the authoritative rendering of the prefix — we just couldn't
        // use windowing for this keystroke. We must not overwrite the
        // anchor with the fresh fallback top (which may have picked a
        // different decomposition driven by whole-buffer LM scores).
        var windowFallback = false
        if effectiveWindowed && grammarParses.allSatisfy({ !Self.isAcceptableParse($0) }) {
            effectiveParseInput = normalized
            effectivePrefixBranches = []
            effectiveWindowed = false
            windowFallback = true
            grammarParses = cachedGrammarParses(
                effectiveParseInput,
                maxResults: Self.grammarCandidateBudget(for: effectiveParseInput),
                isFullBuffer: !effectiveWindowed
            )
            grammarParses.removeAll { Self.hasInterleavedLatin($0.output) }
        }

        var grammarCandidates: [RankedGrammarCandidate]
        if effectiveWindowed {
            grammarCandidates = []
            grammarCandidates.reserveCapacity(grammarParses.count * effectivePrefixBranches.count)
            for branch in effectivePrefixBranches {
                for parse in grammarParses {
                    let surface = branch.output + parse.output
                    let reading = branch.reading + parse.reading
                    let tailLM = scoreSurfaceCached(parse.output, context: branch.contextWords, cache: &lmCache)
                    grammarCandidates.append(RankedGrammarCandidate(
                        candidate: Candidate(
                            surface: surface,
                            reading: reading,
                            source: .grammar,
                            score: Double(parse.score)
                        ),
                        legalityScore: parse.legalityScore,
                        aliasCost: parse.aliasCost,
                        parserScore: parse.score,
                        structureCost: parse.structureCost,
                        syllableCount: parse.syllableCount,
                        rarityPenalty: parse.rarityPenalty,
                        lmLogProb: branch.lmScore + tailLM,
                        absorbedMissingFromLM: false
                    ))
                }
            }
        } else {
            grammarCandidates = grammarParses.map { parse in
                RankedGrammarCandidate(
                    candidate: Candidate(
                        surface: parse.output,
                        reading: parse.reading,
                        source: .grammar,
                        score: Double(parse.score)
                    ),
                    legalityScore: parse.legalityScore,
                    aliasCost: parse.aliasCost,
                    parserScore: parse.score,
                    structureCost: parse.structureCost,
                    syllableCount: parse.syllableCount,
                    rarityPenalty: parse.rarityPenalty,
                    lmLogProb: scoreSurfaceCached(parse.output, context: context, cache: &lmCache),
                    absorbedMissingFromLM: false
                )
            }
        }
        // Two branches × tail can converge on the same surface. Keep the
        // higher-LM-scored copy so dedup doesn't drop the winning branch.
        if effectiveWindowed {
            var bestBySurface: [String: Int] = [:]
            var deduped: [RankedGrammarCandidate] = []
            for candidate in grammarCandidates {
                let key = candidate.candidate.surface
                if let existing = bestBySurface[key] {
                    if candidate.lmLogProb > deduped[existing].lmLogProb {
                        deduped[existing] = candidate
                    }
                } else {
                    bestBySurface[key] = deduped.count
                    deduped.append(candidate)
                }
            }
            grammarCandidates = deduped
        }
        // `hasInterleavedLatin` was already applied to `grammarParses` at
        // the two removeAll sites above (primary + window-fallback). The
        // windowed branch merely concatenates `branch.output` (frozen
        // prefix, Myanmar-only) with each already-filtered parse output,
        // so a repeat filter here cannot reject anything new.

        // Lexicon lookup runs BEFORE the grammar sort so that absorbed
        // lexicon scores (added to matching grammar candidates in place)
        // are visible to the composite-score comparator. Sorting first
        // and absorbing after leaves `candidate.score` stale during the
        // sort, which previously let surfaces like `မ်` (score 0) win
        // over `အံ` for buffer `an` even though absorption would boost
        // `အံ` to score ~643.
        //
        // When windowed, run one lexicon lookup against the active tail
        // and compose each hit with the frozen-prefix branches — otherwise
        // long sentences lose lexicon-corrected renderings entirely (the
        // tail-only parser produces literal digraphs like `s+h` where a
        // real word like `ရှ` should appear). Outside windowing, look up
        // the full buffer as before.
        let previousSurface = context.last
        let aliasPrefix = Romanization.aliasReading(normalized)
        let composePrefix = Romanization.composeLookupKey(normalized)
        let lexiconCandidates: [Candidate]
        if effectiveWindowed {
            let tailAlias = Romanization.aliasReading(effectiveParseInput)
            let branchPrevSurface = effectivePrefixBranches.first?.contextWords.last
                ?? previousSurface
            let tailHits = candidateStore.lookup(
                prefix: tailAlias,
                previousSurface: branchPrevSurface
            )
            // Only promote lexicon entries whose reading is exactly the
            // tail — partial prefix matches would drift keystroke-to-keystroke
            // and destabilize the frozen-prefix anchor for long sentences.
            let exactTailHits = tailHits.filter {
                Romanization.aliasReading($0.reading) == tailAlias
            }
            var composed: [Candidate] = []
            composed.reserveCapacity(exactTailHits.count * effectivePrefixBranches.count)
            for branch in effectivePrefixBranches {
                for hit in exactTailHits {
                    composed.append(Candidate(
                        surface: branch.output + hit.surface,
                        reading: branch.reading + hit.reading,
                        source: hit.source,
                        score: hit.score
                    ))
                }
            }
            lexiconCandidates = composed
        } else {
            lexiconCandidates = candidateStore.lookup(
                prefix: aliasPrefix,
                previousSurface: previousSurface
            )
        }

        // Word-lattice decoder (task: long-sentence quality debt). The
        // syllable-parser DP loses the LM-correct surface early in long
        // multi-word buffers because its beam prunes by alias cost — by
        // the time the engine's LM comparator runs, the right candidate
        // is no longer reachable. The lattice decoder reads the same
        // buffer through an arc graph (lexicon + syllable fallback)
        // with the LM in the Viterbi loop, so the correct surface
        // stays alive across word boundaries. Outputs land here as
        // first-class grammar candidates so the existing composite
        // / LM-dominance ranking picks between them and the parser
        // candidates on the usual signals.
        //
        // Length gate: for short buffers (below `latticeMinReadingLen`)
        // the parser + whole-buffer lexicon lookup already reach the
        // right answer, and lattice injection does more harm than good —
        // the lexicon carries rare pedagogical / Pali surfaces
        // (independent-vowel forms `ဦ`, `ဧ`, literary `ကြဧ`) whose raw
        // rank_score would win the synthetic-score comparison against
        // clean parser output. Gating at ≥8 chars keeps the lattice
        // focused on the multi-word regime where it actually moves the
        // needle.
        // Run the lattice decoder on the full normalized buffer, not
        // on the active tail. Windowed / frozen-prefix decoding can
        // commit a wrong parse in the prefix (e.g. `ဆစ်ဟွား` instead
        // of `ဆီသွား`) which the tail-only lattice cannot undo. Running
        // lattice on the full buffer lets it re-segment the whole
        // sentence in one pass — the lexicon's suffix cache
        // (`exactLookupCache`) keeps repeated keystrokes cheap.
        //
        // Because the lattice output represents the entire buffer
        // from scratch, we skip the frozen-prefix prepend path that
        // would otherwise apply in windowed mode.
        // The lattice needs a real (vocabulary-bearing) LM to rank
        // its word-arc alternatives — without one the Viterbi
        // collapses to "highest lexicon rank_score wins" and that
        // surfaces rare / literary variants (`တဦ` for `tu`, `ဦ`/`ဧ`
        // forms) in place of the common reading. Skip the decoder
        // under `NullLanguageModel` (tests that construct the engine
        // with just a store).
        let latticeOutputs: [WordLatticeDecoder.LatticeCandidate]
        if normalized.count >= Self.latticeMinReadingLen
            && languageModel.hasVocabulary {
            latticeOutputs = latticeDecoder.decode(
                reading: normalized,
                baseContext: context
            )
        } else {
            latticeOutputs = []
        }
        if !latticeOutputs.isEmpty {
            // Rebuild the surface index after each injection path; we
            // want lattice candidates to be deduped against existing
            // grammar candidates too.
            var injectIndex: [String: Int] = [:]
            for (idx, cand) in grammarCandidates.enumerated() {
                injectIndex[cand.candidate.surface] = idx
            }
            // Only inject lattice candidates whose LM score is within
            // a reasonable margin of the lattice's top. The tail of
            // the lattice output holds rare variants (retroflex `ဌ`,
            // tone-dot aliases, punctuation artefacts) that would
            // otherwise pollute the anchor history during progressive
            // typing — at an intermediate buffer length the weak-LM
            // variant can win a local tiebreak and then propagate as
            // the committed prefix on subsequent keystrokes.
            let latticeLmTop = latticeOutputs[0].lmLogProb
            let latticeLmFloor = latticeLmTop - Self.latticeLmInjectionMargin
            for (rank, out) in latticeOutputs.enumerated() where out.lmLogProb >= latticeLmFloor {
                let fullSurface = out.surface
                let fullReading = out.reading
                if Self.hasInterleavedLatin(fullSurface) { continue }
                // Lattice's Viterbi LM sum covers the whole buffer
                // (we run decode on `normalized`, not the windowed
                // tail). Use it as-is — arcwise trigram sum is the
                // ranking signal we want, aligned with the word
                // boundaries the lattice actually chose.
                let totalLM = out.lmLogProb
                // Synthetic rank score preserves the lattice's internal
                // order. Sized to be on the same scale as parser DP
                // scores (≤ 20 for a 10-char buffer): log(rank) is the
                // primary input to the composite comparator, and
                // `log(30) - log(10) = 1.1` is a ≈2.75 nat boost
                // against a pure parser candidate. That lets lattice
                // outputs surface in the top but still yields when
                // a parser candidate has a clearly better LM signal
                // (>≈3 nats, which the LM-dominance short-circuit
                // already covers at 1 nat). Top-of-lattice gets 30,
                // dropping by 2 per rank down to a floor of 10.
                let latticeRankScore = Double(max(10, 30 - rank * 2))
                if let existingIdx = injectIndex[fullSurface] {
                    // Same surface already emitted by parser / lexicon.
                    // Give it a modest lattice bonus (not full replace),
                    // and refresh the LM score with the lattice view so
                    // the absorbed candidate benefits from the decoder.
                    let existing = grammarCandidates[existingIdx]
                    grammarCandidates[existingIdx].candidate = Candidate(
                        surface: existing.candidate.surface,
                        reading: existing.candidate.reading,
                        source: existing.candidate.source,
                        score: existing.candidate.score + latticeRankScore
                    )
                    // Prefer the higher of the two LM readings — lattice
                    // uses the same scorer but a different context
                    // chain, so this is a safe max-of-both.
                    if totalLM > existing.lmLogProb {
                        grammarCandidates[existingIdx].lmLogProb = totalLM
                    }
                } else {
                    // Approximate Burmese syllable count by counting
                    // base consonants / independent vowels in the
                    // surface. Using `arcCount` directly under-reports
                    // for compound lexicon arcs (e.g. `အိမ်မှာ` = 1 arc
                    // but 2 syllables), which would let lattice win the
                    // DP-style `syllableCount` tiebreaker unfairly.
                    let approxSyllables = Self.approximateSyllableCount(fullSurface)
                    // Legality per syllable at 120 sits just above the
                    // parser's DP-score-per-syllable (100-110) so the
                    // lattice wins the legality tiebreak in
                    // `grammarCandidateIsBetter` at equal syllableCount.
                    // This is safe because every lattice arc is either a
                    // lexicon hit (curated surface) or a parser-emitted
                    // legal syllable — both are strictly as legal as the
                    // parser's own output.
                    grammarCandidates.append(RankedGrammarCandidate(
                        candidate: Candidate(
                            surface: fullSurface,
                            reading: fullReading,
                            source: .grammar,
                            score: latticeRankScore
                        ),
                        legalityScore: 120 * max(1, approxSyllables),
                        aliasCost: 0,
                        parserScore: Int(latticeRankScore),
                        structureCost: 0,
                        syllableCount: max(1, approxSyllables),
                        rarityPenalty: 0,
                        lmLogProb: totalLM,
                        absorbedMissingFromLM: false
                    ))
                    injectIndex[fullSurface] = grammarCandidates.count - 1
                }
            }
        }

        var grammarSurfaceIndex: [String: Int] = [:]
        for (index, candidate) in grammarCandidates.enumerated() {
            grammarSurfaceIndex[candidate.candidate.surface] = index
        }

        var uniqueLexiconCandidates: [RankedLexiconCandidate] = []
        var seenLexiconSurfaces: Set<String> = []

        for lexiconCandidate in lexiconCandidates {
            if let grammarIndex = grammarSurfaceIndex[lexiconCandidate.surface] {
                grammarCandidates[grammarIndex].candidate = Candidate(
                    surface: grammarCandidates[grammarIndex].candidate.surface,
                    reading: grammarCandidates[grammarIndex].candidate.reading,
                    source: .grammar,
                    score: grammarCandidates[grammarIndex].candidate.score + lexiconCandidate.score
                )
                if languageModel.hasVocabulary {
                    grammarCandidates[grammarIndex].absorbedMissingFromLM =
                        !languageModel.containsSurface(grammarCandidates[grammarIndex].candidate.surface)
                }
                continue
            }

            if seenLexiconSurfaces.insert(lexiconCandidate.surface).inserted {
                uniqueLexiconCandidates.append(
                    RankedLexiconCandidate(
                        candidate: lexiconCandidate,
                        aliasPenalty: Romanization.aliasPenaltyCount(for: lexiconCandidate.reading),
                        aliasReading: Romanization.aliasReading(lexiconCandidate.reading),
                        composeReading: Romanization.composeLookupKey(lexiconCandidate.reading),
                        lmLogProb: scoreSurfaceCached(lexiconCandidate.surface, context: context, cache: &lmCache)
                    )
                )
            }
        }

        // Sort after absorption so the comparator's composite score sees
        // the post-absorption `candidate.score`. Subsequent stages
        // (pruneByLmMargin, promoteAliasAlternate, alternate injection)
        // see a sorted list with the same shape they always did.
        grammarCandidates.sort { lhs, rhs in
            grammarCandidateIsBetter(lhs, than: rhs)
        }
        let appliesYapinPromotion = !effectiveWindowed
            && Self.isYapinPromotionBuffer(effectiveParseInput)

        // TASK-005: when windowed, the inferred-stack surfaces are the
        // tail-only outputs but `grammarCandidates[*].surface` are
        // full `<prefix><tail>` surfaces. Without expanding the
        // preserve set into windowed-aware form, the LM-margin prune
        // drops the kinzi-bearing windowed candidate before the
        // windowed promotion at `bestStrictInferredStackIndex` ever
        // runs — so the rank-0 lift has nothing to lift. Build the
        // expanded set by concatenating each frozen-prefix branch's
        // output with each tail surface in the strict / liberal-kinzi
        // sets. Also keep the tail-only surfaces for the un-windowed
        // path's match.
        var combinedPreserveSurfaces = strictInferredStackOutputs.union(liberalKinziOutputs)
        if effectiveWindowed, !effectivePrefixBranches.isEmpty {
            let originalSet = combinedPreserveSurfaces
            for branch in effectivePrefixBranches {
                for tailSurface in originalSet {
                    combinedPreserveSurfaces.insert(branch.output + tailSurface)
                }
            }
            // TASK-044: when a frozen-prefix branch carries a kinzi
            // sequence (`1004 103A 1039`), the kinzi syllable lives
            // entirely INSIDE the prefix and never reaches the tail-
            // side `inferImplicitStackMarkers` — so the tail-derived
            // `strictInferredStackOutputs` set is empty for the
            // prefix's kinzi, and the windowed-aware expansion above
            // doesn't add anything for it. Without an explicit
            // preserve entry, the LM-margin prune at
            // `pruneGrammarByLmMargin` drops the kinzi-bearing
            // `<branch.output><tail>` combo as soon as a stronger-LM
            // lattice / no-kinzi sibling appears, leaving the
            // candidate panel without ANY kinzi-rendered surface.
            // Preserve every grammar candidate whose surface starts
            // with a kinzi-bearing prefix-branch output. This is a
            // narrow rule — it only fires when the engine has
            // already chosen a kinzi-rendering branch, so it never
            // resurrects unrelated low-LM candidates.
            for branch in effectivePrefixBranches
            where Self.surfaceContainsKinzi(branch.output) {
                for candidate in grammarCandidates
                where candidate.candidate.surface.hasPrefix(branch.output) {
                    combinedPreserveSurfaces.insert(candidate.candidate.surface)
                }
            }
        }
        if appliesYapinPromotion,
           let yapinSurface = Self.yapinPromotionPreservedSurface(
                in: grammarCandidates,
                userBuffer: effectiveParseInput
           ) {
            var preservingGrammarSurfaces = combinedPreserveSurfaces
            preservingGrammarSurfaces.insert(yapinSurface)
            grammarCandidates = pruneGrammarByLmMargin(
                grammarCandidates,
                preservingSurfaces: preservingGrammarSurfaces
            )
        } else {
            grammarCandidates = pruneGrammarByLmMargin(
                grammarCandidates,
                preservingSurfaces: combinedPreserveSurfaces
            )
        }
        grammarCandidates = promoteAliasAlternate(grammarCandidates)
        // Ya-pin typing-intent promotion: if the bare user buffer is
        // the exact digit-stripped form of a ya-pin canonical reading
        // (e.g. `kyay` → `ky2ay`), flip the top pick to the ya-pin
        // sibling (task 07). Only applied in the non-windowed path so
        // long-sentence frozen-prefix ranking is untouched.
        if appliesYapinPromotion {
            grammarCandidates = Self.promoteYapinForExactBareReading(
                grammarCandidates,
                userBuffer: effectiveParseInput
            )
        }

        // Expose disambiguation alternatives that the DP never emits
        // once the primary parse dominates:
        //
        //   * `<C>in+<C>` is a kinzi signal from the user, so the kinzi
        //     parse stays at rank 1 but the non-kinzi segmentation
        //     (`<C>in` + `<C>`) is injected as a lower-ranked option.
        //   * `<y|w|r|h><C>` promotes the leading medial-letter into
        //     an onset consonant silently; inject the buffer-minus-
        //     leading-letter parse so the user sees the "medial
        //     stranded" alternative.
        if !effectiveWindowed {
            let existingSurfaces = Set(grammarCandidates.map { $0.candidate.surface })
            var altInputs: [String] = []
            if let dropped = Self.dropKinziPlus(effectiveParseInput) { altInputs.append(dropped) }
            if let stripped = Self.stripLeadingMedialPromotion(effectiveParseInput) {
                altInputs.append(stripped)
            }
            var seenExtras = existingSurfaces
            for alt in altInputs {
                let altParses = parser.parseCandidates(
                    alt,
                    maxResults: 2,
                    isFullBuffer: !effectiveWindowed
                )
                for parse in altParses where !Self.hasInterleavedLatin(parse.output)
                    && !seenExtras.contains(parse.output) {
                    seenExtras.insert(parse.output)
                    grammarCandidates.append(RankedGrammarCandidate(
                        candidate: Candidate(
                            surface: parse.output,
                            reading: parse.reading,
                            source: .grammar,
                            score: Double(parse.score)
                        ),
                        legalityScore: parse.legalityScore,
                        aliasCost: parse.aliasCost,
                        parserScore: parse.score,
                        structureCost: parse.structureCost,
                        syllableCount: parse.syllableCount,
                        rarityPenalty: parse.rarityPenalty,
                        lmLogProb: scoreSurfaceCached(parse.output, context: context, cache: &lmCache),
                        absorbedMissingFromLM: false
                    ))
                }
            }
        }

        // History lookup uses the same alias key as the lexicon so stored
        // reads (written by `recordSelection`) line up exactly with reads.
        // Unlike lexicon candidates, history entries carry a self-contained
        // surface that isn't composed with the frozen prefix, so they are
        // safe to surface even when windowing is active — otherwise a user
        // who committed a long phrase once wouldn't see it again the next
        // time they typed the same reading (the buffer crosses the window
        // threshold long before they reach the end).
        let historyEnabled = settings?.learningEnabled ?? true
        let historyCandidates: [Candidate] = historyEnabled
            ? historyStore.lookup(prefix: aliasPrefix, previousSurface: previousSurface)
            : []
        cacheLock.lock()
        lastHistoryKey = aliasPrefix
        cacheLock.unlock()

        uniqueLexiconCandidates.sort { lhs, rhs in
            lexiconCandidateIsBetter(lhs, than: rhs, aliasPrefix: aliasPrefix, composePrefix: composePrefix)
        }
        uniqueLexiconCandidates = pruneByLmMargin(uniqueLexiconCandidates, keyPath: \.lmLogProb)

        let primaryGrammar = Array(grammarCandidates.prefix(3))
        let remainingGrammar = Array(grammarCandidates.dropFirst(3))
        let exactAliasPrefixes = Set(Romanization.lookupAliasReadings(for: normalized).map(\.aliasReading))
        let exactComposePrefixes = Set(Romanization.lookupComposeReadings(for: normalized).map(\.composeReading))
        let exactAliasLexicon = uniqueLexiconCandidates.filter { exactAliasPrefixes.contains($0.aliasReading) }
        let exactComposeLexicon = uniqueLexiconCandidates.filter {
            !exactAliasPrefixes.contains($0.aliasReading) && exactComposePrefixes.contains($0.composeReading)
        }
        let prioritizedLexicon = Array(
            (exactAliasLexicon.isEmpty ? exactComposeLexicon : exactAliasLexicon)
                .prefix(2)
        )
        let prioritizedKeys = Set(prioritizedLexicon.map(lexiconCandidateKey))
        let trailingLexicon = uniqueLexiconCandidates.filter { !prioritizedKeys.contains(lexiconCandidateKey($0)) }

        let promotedYapinGrammarFirst = appliesYapinPromotion
            && primaryGrammar.first.map { Self.isYapinReading($0.candidate.reading) } == true

        var merged: [Candidate]
        let primaryGrammarStart: Int
        if promotedYapinGrammarFirst, let firstGrammar = primaryGrammar.first {
            merged = []
            merged.append(firstGrammar.candidate)
            primaryGrammarStart = 1
            for lexiconCandidate in prioritizedLexicon where merged.count < candidatePageSize {
                if !merged.contains(where: { $0.surface == lexiconCandidate.candidate.surface }) {
                    merged.append(lexiconCandidate.candidate)
                }
            }
        } else {
            merged = prioritizedLexicon.map(\.candidate)
            primaryGrammarStart = 0
        }

        if primaryGrammarStart == 0 {
            for grammarCandidate in primaryGrammar where merged.count < candidatePageSize {
                merged.append(grammarCandidate.candidate)
            }
        } else {
            for grammarCandidate in primaryGrammar.dropFirst(primaryGrammarStart) where merged.count < candidatePageSize {
                merged.append(grammarCandidate.candidate)
            }
        }

        for lexiconCandidate in trailingLexicon where merged.count < candidatePageSize {
            merged.append(lexiconCandidate.candidate)
        }

        for grammarCandidate in remainingGrammar where merged.count < candidatePageSize {
            merged.append(grammarCandidate.candidate)
        }

        // History promotion: the user previously committed these surfaces
        // under the same alias key, so float them to the top. Walk lowest
        // score first so the highest-scoring history entry lands at index 0
        // after successive front-inserts. Surfaces already in `merged` are
        // moved; unseen surfaces are injected (the entry was legal when
        // first committed, so it's safe to resurface).
        for historyCandidate in historyCandidates.sorted(by: { $0.score < $1.score }) {
            if let existing = merged.firstIndex(where: { $0.surface == historyCandidate.surface }) {
                let keeper = merged.remove(at: existing)
                merged.insert(keeper, at: 0)
            } else {
                merged.insert(historyCandidate, at: 0)
            }
        }

        // TASK-019: ensure strict-inferred kinzi surfaces are always
        // present in `merged` even when the candidate page size has
        // already filled up with other parses. Without this, a buffer
        // with many medial / cluster variants (e.g. `manggyi` →
        // `မငဂြီ`, `မငဂျီ`, `မန်ဂဂြီ`, …) can crowd out the inferred
        // kinzi candidate before `bestStrictInferredStackIndex` gets
        // a chance to promote it. The injection happens in-place;
        // duplicates are filtered.
        if !strictInferredStackOutputs.isEmpty {
            let mergedSurfaces = Set(merged.map(\.surface))
            for grammarCandidate in grammarCandidates
            where strictInferredStackOutputs.contains(grammarCandidate.candidate.surface)
                && !mergedSurfaces.contains(grammarCandidate.candidate.surface) {
                merged.append(grammarCandidate.candidate)
            }
        }
        merged = Self.expandAaVariants(merged)
        merged = Self.sanitizeOrphanZwnj(merged)
        merged = Self.sanitizeMalformedMyanmarMarks(merged)
        merged = Self.sanitizeIndepVowelVirama(merged)
        // TASK-052: explicit-`+` two-syllable forms whose surface
        // contains adjacent independent-vowel scalars (`a+i` →
        // `1021 1021 102E`, `a+u` → `1021 1021 1030`, `a+aung` →
        // `1021 1021 1031 102C 1004 103A`, …) are user-intentional
        // and must not be filtered by `sanitizeAdjacentIndependent
        // Vowels`. Pass them through as a preserved set.
        merged = Self.sanitizeAdjacentIndependentVowels(
            merged,
            preservedSurfaces: strictInferredStackOutputs
        )
        merged = Self.sanitizeDoubledCodaChain(merged)
        merged = Self.sanitizeMultiClusterOnSingleAnchor(merged)

        // TASK-031: `effectiveParseInput.contains("+")` no longer
        // gates this promotion. The original gate was based on the
        // (incorrect) assumption that user-typed `+` already
        // guarantees the parser's stack-respecting surface wins
        // ranking; in practice the LM signal can flip a sibling
        // (anusvara/nya-asat-na/etc.) above the user's intent on
        // short buffers, so we route `+`-bearing buffers through the
        // same promotion path the inferred-`+` cases use. The
        // `strictInferredStackOutputs` set was populated upstream
        // from grammar parses whose reading exactly matches
        // `effectiveParseInput` — that's the discriminator that
        // keeps the promotion targeted at "user-typed-`+`-respecting"
        // surfaces and avoids re-promoting variant parses (e.g.
        // `kan2+ga` retroflex sibling).
        if !effectiveWindowed,
           !strictInferredStackOutputs.isEmpty,
           let idx = Self.bestStrictInferredStackIndex(
               in: merged,
               strictInferredStackOutputs: strictInferredStackOutputs
           ) {
            // TASK-031: when the buffer carries an explicit user-
            // typed `+`, skip the promotion if a lexicon-source
            // candidate already occupies rank 0. Lexicon hits are
            // the strongest signal — the user composed a word that
            // matches a curated dictionary entry — and must not be
            // displaced by a grammar-side strict-stack candidate.
            // The implicit-inference path (no `+` in the buffer)
            // continues to promote unconditionally because there's
            // no user-explicit signal that would justify deferring
            // to lexicon over the inferred stack.
            //
            // TASK-056: narrow the lexicon-rank-0 protection. When
            // the rank-0 lexicon hit's reading does NOT contain
            // `+`, the lexicon entry describes a *different*
            // segmentation than the user's `+`-bearing input — e.g.
            // user typed `k+ya` (intent: two syllables `ka` + `ya`),
            // lexicon hit is `kya` reading=`kya` (the medial
            // cluster `ကြ`). Per CLAUDE.md §6, the user's explicit
            // `+` must not be displaced by an LM/lexicon-favoured
            // segmentation that ignores the boundary. Only protect
            // lexicon rank-0 when its reading also reflects the
            // user's `+` placement.
            let lexiconAtSlotZero = displayBuffer.contains("+")
                && !merged.isEmpty
                && merged[0].source == .lexicon
                && merged[0].reading.contains("+")
            if !lexiconAtSlotZero {
                let keeper = merged.remove(at: idx)
                merged.insert(keeper, at: 0)
            }
        }

        // Windowed-buffer counterpart of the promotion above (TASK-001).
        // `strictInferredStackOutputs` carries the tail-only surface
        // produced by the inferred parse (e.g. `မင်္ဂလာပါ`); the
        // windowed candidates in `merged` are full surfaces of the form
        // `<frozen prefix><tail>`. Build the windowed-aware set of full
        // surfaces by concatenating each frozen branch's output with
        // every tail-only strict-stack surface, then promote the best
        // matching merged candidate to rank 0. Frozen-prefix-resident
        // inference sites are excluded by construction: the strict set
        // only ever contains tail-derived outputs.
        // TASK-031: same gate-lift as the non-windowed branch above.
        // The windowed path computes `windowedStrictOutputs` =
        // `<frozen prefix><tail>` for each tail surface in
        // `strictInferredStackOutputs`; the membership check still
        // applies, so explicit-`+` buffers that window across the
        // composition boundary participate in the rank-0 promotion.
        if effectiveWindowed,
           !effectivePrefixBranches.isEmpty,
           !strictInferredStackOutputs.isEmpty {
            var windowedStrictOutputs: Set<String> = []
            windowedStrictOutputs.reserveCapacity(
                effectivePrefixBranches.count * strictInferredStackOutputs.count
            )
            for branch in effectivePrefixBranches {
                for tailSurface in strictInferredStackOutputs {
                    windowedStrictOutputs.insert(branch.output + tailSurface)
                }
            }
            if let idx = Self.bestStrictInferredStackIndex(
                in: merged,
                strictInferredStackOutputs: windowedStrictOutputs
            ) {
                let keeper = merged.remove(at: idx)
                merged.insert(keeper, at: 0)
            }
        }

        // Pali loanword fallback: cross-class virama stacks like
        // ပဒ္မ / ဗန္ဒန / ဂန္ဒ are not produced by Grammar.isValidStack
        // (which is restricted to native same-class pairs) and are not
        // present as lexicon entries when the corpus does not surface
        // them. Inject the canonical stacked surface at rank 1 for the
        // exact bare reading so the engine returns the orthographic
        // form a typist reaches for. Compound buffers that just happen
        // to start with one of these readings (e.g. `gandakar`) match
        // the regular grammar/lexicon path and never hit this branch.
        if let paliSurface = Self.paliStackOverrideSurface(for: normalized) {
            if let existing = merged.firstIndex(where: { $0.surface == paliSurface }) {
                let keeper = merged.remove(at: existing)
                merged.insert(keeper, at: 0)
            } else {
                merged.insert(Candidate(
                    surface: paliSurface,
                    reading: normalized,
                    source: .grammar,
                    score: 100
                ), at: 0)
            }
        }

        // Bare-vowel override: `i` → အိ, `ee` → အီ. Grammar siblings
        // (`ည်`, `ယ်ယ်`, long-i / short-i) remain in the panel — this
        // only flips the top (task 08).
        if let bareVowelSurface = Self.bareVowelOverrideSurface(for: normalized) {
            if let existing = merged.firstIndex(where: { $0.surface == bareVowelSurface }) {
                let keeper = merged.remove(at: existing)
                merged.insert(keeper, at: 0)
            } else {
                merged.insert(Candidate(
                    surface: bareVowelSurface,
                    reading: normalized,
                    source: .grammar,
                    score: 100
                ), at: 0)
            }
        }

        // `ai` diphthong override (task 04): when the buffer starts
        // with `aing<…>` and the merged panel still carries a
        // diphthong-anchored candidate (often demoted by an LM that
        // sees the short-i + na-asat sibling more often in the
        // corpus), promote it. The short-i sibling stays in the
        // panel as a lower-ranked alternative.
        if Self.aiDiphthongOverrideApplies(to: normalized) {
            if let idx = merged.firstIndex(where: {
                Self.candidateLeadsWithAiDiphthong($0.surface)
            }), idx > 0 {
                let keeper = merged.remove(at: idx)
                merged.insert(keeper, at: 0)
            }
        }

        // Anchor promotion: when the top candidate drifts away from a
        // previously established prefix, promote any candidate that
        // preserves the anchor surface. Walk the anchor history from
        // deepest to shallowest: intermediate anchors may have held
        // temporarily wrong syllable decompositions (e.g. "kah" → ကအ
        // before "kaht" → ကထ resolved), so skip those and find the
        // deepest anchor whose surface actually appears in a candidate.
        // Surface comparison strips ZWSPs because lexicon entries may
        // contain U+200B word-boundary markers that grammar-generated
        // surfaces lack.
        //
        // A history-sourced top outranks anchor stability: the user
        // explicitly committed that surface previously, so displacing it
        // with a parser-derived anchor extension would revert a deliberate
        // pick.
        if !merged.isEmpty, merged[0].source != .history {
            let topLM = scoreSurfaceCached(
                merged[0].surface, context: context, cache: &lmCache
            )
            var promoted = false
            for anchor in historySnapshot.reversed() {
                guard !anchor.normalized.isEmpty,
                      normalized.hasPrefix(anchor.normalized),
                      normalized.count > anchor.normalized.count,
                      anchor.normalized.count >= anchorCommitThreshold
                else { continue }
                let anchorKey = Self.stripZWSP(anchor.surface)
                // Already matching — no promotion needed.
                if Self.scalarHasPrefix(Self.stripZWSP(merged[0].surface), anchorKey) {
                    promoted = true
                    break
                }
                if let idx = merged.firstIndex(where: { Self.scalarHasPrefix(Self.stripZWSP($0.surface), anchorKey) }) {
                    // LM-margin guard (tasks 02 / 05): if the LM clearly
                    // prefers the current top over the anchor-matching
                    // candidate, the recorded anchor reflects a transient
                    // segmentation/medial pick that the longer buffer no
                    // longer supports. Skip the promotion and let the
                    // LM-best surface lead. The anchor remains in history
                    // so a future keystroke whose LM evidence does match
                    // it can still resurrect it.
                    //
                    // Exception (task 02 long-sentence regression): when
                    // the anchor was committed AT a word boundary (its
                    // recorded buffer ends in punctuation `.` / `:` /
                    // `+`) AND the candidate differs from the current
                    // top only in ya-pin / ya-yit medial choice, bypass
                    // the LM-margin guard. A boundary-aligned anchor
                    // carries a complete-word lexicon commitment
                    // (`phyar:` → `ဖျား`); re-scoring the trigram LM at
                    // longer buffer fragments can flip the medial against
                    // that lexicon evidence (`narn` after `kaphyar:nar`
                    // sits outside `ဖျား`'s bigram cache and the LM
                    // floor flips). A mid-word anchor (typed `b` in
                    // `kywantawkalaungb` before the user reveals which
                    // word) is unstable by construction — no lexicon
                    // evidence locked in the medial yet — so the LM
                    // guard remains in effect.
                    let candidateStrippedHere = Self.stripZWSP(merged[idx].surface)
                    let topStrippedHere = Self.stripZWSP(merged[0].surface)
                    let isMedialOnlySwap = candidateStrippedHere.count == topStrippedHere.count
                        && Self.normalizeYaPinYaYit(topStrippedHere)
                            == Self.normalizeYaPinYaYit(candidateStrippedHere)
                    let anchorAtWordBoundary: Bool = {
                        guard let lastChar = anchor.normalized.last else { return false }
                        // Composing-punctuation suffixes that the engine
                        // treats as syllable / word terminators in the
                        // user's typed buffer: visarga `:`, creaky-tone
                        // `.`, and explicit cluster marker `+`.
                        return lastChar == ":" || lastChar == "." || lastChar == "+"
                    }()
                    if !(isMedialOnlySwap && anchorAtWordBoundary) {
                        let candidateLM = scoreSurfaceCached(
                            merged[idx].surface, context: context, cache: &lmCache
                        )
                        if topLM - candidateLM > Self.lmDominanceThreshold {
                            continue
                        }
                        // TASK-004: symmetric guard — when the anchor-
                        // matching candidate has STRONGER LM than the
                        // comparator-chosen top AND the surfaces differ
                        // by more than a medial / coda swap (i.e. the
                        // comparator picked a re-segmentation despite
                        // worse LM, signalling the structural factors
                        // it weighs above LM disagree with the
                        // anchor-extension reading), refuse the
                        // promotion. The medial-swap and coda-swap
                        // subcases continue to promote because the
                        // comparator there is just splitting hairs on
                        // per-syllable medial / coda choice;
                        // re-segmentation cases (where the candidate
                        // has different syllable structure) are the
                        // ones the comparator's structural factors
                        // are designed to resolve.
                        let isCodaSwap = Self.isCodaOnlySingleScalarDifference(
                            candidateStrippedHere,
                            topStrippedHere
                        )
                        if candidateLM - topLM > Self.lmDominanceThreshold,
                           !isMedialOnlySwap,
                           !isCodaSwap {
                            continue
                        }
                    }
                    let keeper = merged.remove(at: idx)
                    merged.insert(keeper, at: 0)
                    promoted = true
                    break
                }
            }
            // No existing candidate matched any anchor. The full-buffer
            // parse has the correct syllable structure but may have
            // drifted in ya-pin/ya-yit medial choice. Check whether the
            // difference is only in medials — if so, create a variant
            // with the anchor's medial swapped in. This preserves the
            // correct syllable count while keeping the user's previously-
            // seen prefix stable on screen.
            //
            // Same LM-margin guard applies here: only synthesise the
            // medial-swapped variant when the LM does not strongly
            // prefer the current top. Otherwise the synthesis would
            // freeze a medial that LM has since out-voted.
            if !promoted {
                let topStripped = Self.stripZWSP(merged[0].surface)
                for anchor in historySnapshot.reversed() {
                    guard !anchor.normalized.isEmpty,
                          normalized.hasPrefix(anchor.normalized),
                          normalized.count > anchor.normalized.count,
                          anchor.normalized.count >= anchorCommitThreshold
                    else { continue }
                    let anchorStripped = Self.stripZWSP(anchor.surface)
                    if Self.viramaInsensitiveHasPrefix(topStripped, anchorStripped)
                        && !Self.scalarHasPrefix(topStripped, anchorStripped) {
                        let variant = Self.substituteViramaAnchor(
                            in: merged[0].surface,
                            matching: anchorStripped
                        )
                        let variantLM = scoreSurfaceCached(
                            variant, context: context, cache: &lmCache
                        )
                        if topLM - variantLM > Self.lmDominanceThreshold {
                            continue
                        }
                        merged.insert(Candidate(
                            surface: variant,
                            reading: merged[0].reading,
                            source: merged[0].source,
                            score: merged[0].score
                        ), at: 0)
                        break
                    }
                    // Check if the surfaces match after normalizing
                    // ya-pin (U+103B) ↔ ya-yit (U+103C) medials.
                    let topNorm = Self.normalizeYaPinYaYit(topStripped)
                    let anchorNorm = Self.normalizeYaPinYaYit(anchorStripped)
                    if topNorm.hasPrefix(anchorNorm)
                        && !topStripped.hasPrefix(anchorStripped) {
                        let variant = Self.substituteMedials(
                            in: merged[0].surface,
                            matching: anchorStripped
                        )
                        let variantLM = scoreSurfaceCached(
                            variant, context: context, cache: &lmCache
                        )
                        if topLM - variantLM > Self.lmDominanceThreshold {
                            continue
                        }
                        merged.insert(Candidate(
                            surface: variant,
                            reading: merged[0].reading,
                            source: merged[0].source,
                            score: merged[0].score
                        ), at: 0)
                        break
                    }
                }
            }
        }

        // Record the new anchor for the next update. Capturing the top
        // candidate's (normalized, surface, reading) means subsequent
        // keystrokes that extend `normalized` reuse this exact rendering
        // rather than re-parsing and potentially picking a different
        // decomposition. During a window-fallback we keep the existing
        // anchor — the rendering the user still sees on screen — rather
        // than committing the fallback top that may have drifted.
        if !windowFallback {
            cacheLock.lock()
            // Skip history candidates when picking the anchor: their surface
            // is the full stored rendering for a longer reading that still
            // begins with the currently-typed prefix, so capturing it as
            // the anchor for `normalized` pairs a short key with an overly
            // long surface. A later windowed update would reuse that anchor
            // as a frozen prefix and concatenate a fresh tail parse,
            // producing candidates shaped like `<full history surface> +
            // <tail re-rendered>`. The non-history top reflects the actual
            // syllable rendering of the typed chars and is safe to anchor.
            if let top = merged.first(where: { $0.source != .history }) {
                // Prune prior entries that are stale: either (a) their
                // normalized is not a prefix of the current buffer (user
                // backspaced/diverged), or (b) their surface is not a
                // prefix of the new top's surface (an intermediate
                // decomposition that was superseded — e.g. step 11 "kah"
                // → ကအ gets pruned when step 12 "kaht" → ကထ resolves
                // differently). This prevents stale anchors from being
                // used in synthesis and producing extra syllable splits.
                let topStripped = Self.stripZWSP(top.surface)
                let topScalars = Array(topStripped.unicodeScalars)
                anchorHistory.removeAll { anchor in
                    if !normalized.hasPrefix(anchor.normalized) { return true }
                    let anchorStripped = Self.stripZWSP(anchor.surface)
                    if !Self.scalarHasPrefix(topStripped, anchorStripped) { return true }
                    // Anchor's last consonant or medial was extended by
                    // an additional sign in the new top (e.g. anchor
                    // `...ဘ` followed by a medial `ြ` in top `...ဘြ`, or
                    // anchor `...ပြ` followed by a vowel `ီ` in top
                    // `...ပြီ`). Reusing that stale anchor would prevent
                    // the extension from forming in subsequent windowing.
                    let anchorScalarCount = anchorStripped.unicodeScalars.count
                    if anchorScalarCount > 0,
                       anchorScalarCount < topScalars.count,
                       let last = anchorStripped.unicodeScalars.last,
                       Myanmar.isConsonant(last) || Myanmar.isMedial(last),
                       Self.isMedialOrMarker(topScalars[anchorScalarCount]) {
                        return true
                    }
                    return false
                }
                // Replace the last entry if it has the same normalized
                // length (we're updating the same checkpoint, not adding).
                if let last = anchorHistory.last, last.normalized == normalized {
                    anchorHistory.removeLast()
                }
                // TASK-004: gate anchor recording on the LM dominance
                // of the chosen top over its nearest sibling. A weak
                // top pick (LM gap < `lmDominanceThreshold` nats) at
                // an intermediate buffer length shouldn't lock in a
                // transient syllable rendering that the longer buffer
                // might re-segment (`achitthone` typed
                // letter-by-letter would otherwise freeze a length-9
                // anchor `အချစ်သွံ` and resist the length-10
                // re-segmentation `အချစ်သိုနယ်`).
                //
                // Two carve-outs preserve legitimate anchor
                // stability:
                //  - `normalized.count < anchorCommitThreshold` (8):
                //    short anchors don't trigger the post-merge
                //    promotion path anyway, so the gate is moot.
                //  - The buffer ends in a word-boundary marker
                //    (`:`, `.`, `+`): the user has explicitly closed
                //    a word, and the anchor encodes a complete-word
                //    lexicon commitment that downstream re-scoring
                //    must respect (e.g. `kaphyar:` → `ဖျား`). The
                //    same boundary check governs the existing
                //    medial-swap exception in the anchor-promotion
                //    path above.
                let anchorAtWordBoundary: Bool = {
                    guard let lastChar = normalized.last else { return false }
                    return lastChar == ":" || lastChar == "." || lastChar == "+"
                }()
                let shortAnchor = normalized.count < anchorCommitThreshold
                let recordAnchor: Bool
                if shortAnchor || anchorAtWordBoundary {
                    recordAnchor = true
                } else {
                    let topLMForAnchor = scoreSurfaceCached(
                        top.surface, context: context, cache: &lmCache
                    )
                    var nextSiblingLM: Double = -.infinity
                    var siblingsScanned = 0
                    // Cap the sibling scan at 4 — the merged list is
                    // comparator-sorted, so the strongest competitors
                    // sit at the head. Looking past the first few
                    // doesn't change the dominance check materially
                    // and keeps the per-keystroke cost flat.
                    for sibling in merged.dropFirst()
                    where sibling.surface != top.surface
                        && sibling.source != .history {
                        let siblingLM = scoreSurfaceCached(
                            sibling.surface, context: context, cache: &lmCache
                        )
                        if siblingLM > nextSiblingLM {
                            nextSiblingLM = siblingLM
                        }
                        if nextSiblingLM >= topLMForAnchor { break }
                        siblingsScanned += 1
                        if siblingsScanned >= 4 { break }
                    }
                    recordAnchor = nextSiblingLM == -.infinity
                        || topLMForAnchor - nextSiblingLM >= Self.lmDominanceThreshold
                }
                if recordAnchor {
                    anchorHistory.append(PrefixAnchor(
                        normalized: normalized,
                        surface: top.surface,
                        reading: top.reading
                    ))
                    if anchorHistory.count > Self.maxAnchorHistory {
                        anchorHistory.removeFirst(anchorHistory.count - Self.maxAnchorHistory)
                    }
                }
            }
            cacheLock.unlock()
        }

        // Attach leading literal, digit prefix, and literal tail to each
        // candidate surface.
        let hasAffixes = !leadingLiteral.isEmpty || !digitPrefix.isEmpty || !effectiveTail.isEmpty
        let mergedWithAffixes: [Candidate]
        if !hasAffixes {
            mergedWithAffixes = merged
        } else {
            // TASK-043: drop multi-syllable lexicon prefix-match lemmas
            // before concatenating the literal tail / digit affix. The
            // `merged` list contains:
            //   (a) parser/grammar surfaces (and exact-alias/exact-
            //       compose lexicon hits absorbed into grammar at
            //       merge time) whose reading equals `normalized`, and
            //   (b) lexicon prefix-match surfaces whose reading is a
            //       strict superset of `normalized` (the SQLite
            //       `LIMIT 20` returns lemmas whose alias-readings
            //       *start with* the prefix, not just match it).
            // The affix concatenation is only meaningful for (a) — the
            // user's tail letter / digit / punct-run is a literal
            // continuation of the syllable they composed. For (b) the
            // dropped tail belongs to a *different* syllable than the
            // one the lexicon lemma's reading describes; concatenating
            // it produces a fabricated `<lemma>+<tail>` non-word like
            // `ယုံကြည်ချက်အူ` (`belief`+`အူ`) or
            // `ကာကွယ်ရေးဦးစီးချုပ်၁` (`Defense-Service-Chief-1`).
            //
            // Filter rule: drop a candidate iff
            //   - source == .lexicon (exact-reading lexicon hits with
            //     a matching grammar surface get their source rewritten
            //     to .grammar at merge time, so .lexicon here is
            //     necessary AND sufficient for "prefix-only match"
            //     after the un-windowed merge), AND
            //   - the candidate's reading's alias / compose key does
            //     NOT equal `aliasPrefix` / `composePrefix` (defensive
            //     — covers the rare case where an exact-reading
            //     lexicon hit slipped through without being absorbed
            //     into grammar).
            //
            // Single-trailing-punct (`kar:`, `kar.`) is unaffected
            // because those compose into the candidate via the bare-
            // consonant-tone path before the affix loop runs (TASK-014
            // / TASK-049); the `effectiveTail` is empty by the time
            // we get here. Trailing-punct RUNS of length ≥ 2 (`kya..`,
            // `kya::`) leave a residual literal punct in
            // `effectiveTail` and DO trigger the filter.
            let exactReadingFilterApplies = !effectiveTail.isEmpty
                || !digitPrefix.isEmpty
            func candidateIsLexiconPrefixOnly(_ c: Candidate) -> Bool {
                guard c.source == .lexicon else { return false }
                let candAliasKey = Romanization.aliasReading(c.reading)
                if candAliasKey == aliasPrefix { return false }
                let candComposeKey = Romanization.composeLookupKey(c.reading)
                if candComposeKey == composePrefix { return false }
                return true
            }
            let burmesePrefix = Self.arabicToBurmeseDigits(digitPrefix)
            var expanded: [Candidate] = []
            var seen: Set<String> = []
            for candidate in merged {
                if exactReadingFilterApplies,
                   candidateIsLexiconPrefixOnly(candidate) {
                    continue
                }
                let candidateTail = effectiveTail
                let hasDigitAffixes = Self.containsDigit(digitPrefix) || Self.containsDigit(candidateTail)
                if leadingLiteral.isEmpty && digitPrefix.isEmpty && candidateTail.isEmpty {
                    if seen.insert(candidate.surface).inserted {
                        expanded.append(candidate)
                    }
                    continue
                }
                // Affixes (leading literal, digit prefix, literal tail)
                // are concatenated onto the surface but never reach the
                // parser — the inner `candidate.reading` only covers the
                // composable middle. Replace it with the full display
                // buffer so `recordSelection` keys history on what the
                // user actually typed, not the truncated middle (task 05
                // follow-up — the original fix only patched the punct-
                // split recursion paths). Mirrors the override pattern
                // used at lines 339-346 / 382-389.
                let fullReading = displayBuffer
                if hasDigitAffixes {
                    let primary = leadingLiteral + burmesePrefix + candidate.surface + Self.arabicToBurmeseDigits(candidateTail)
                    if seen.insert(primary).inserted {
                        expanded.append(Candidate(
                            surface: primary,
                            reading: fullReading,
                            source: candidate.source,
                            score: candidate.score
                        ))
                    }
                    let secondary = leadingLiteral + digitPrefix + candidate.surface + candidateTail
                    if secondary != primary, seen.insert(secondary).inserted {
                        expanded.append(Candidate(
                            surface: secondary,
                            reading: fullReading,
                            source: candidate.source,
                            score: candidate.score
                        ))
                    }
                } else {
                    let surface = leadingLiteral + digitPrefix + candidate.surface + candidateTail
                    // TASK-014: when the candidate surface ends in a
                    // bare base consonant (no trailing dep-vowel /
                    // tone marker / asat) and the literal tail begins
                    // with `:` or `.`, emit a tone-bearing sibling
                    // (visarga / creaky tone on the consonant's
                    // inherent-`a`) at rank 0 with the literal-tail
                    // form retained at rank 1. The user's natural
                    // typing of `<C>:` / `<C>.` is the heavy / creaky
                    // tone; the literal fallback stays accessible for
                    // English-text-mid-buffer cases.
                    //
                    // TASK-049: extend the same logic to a tail of
                    // shape `<Myanmar-prefix><:|.>` — when the right-
                    // shrink probe drops a longer tail
                    // (`+ka:` for `ka+ka+ka:`) and the tail composer
                    // renders the prefix verbatim while preserving
                    // the trailing tone marker, the tone still
                    // belongs to the END of the full surface
                    // (candidate.surface + tail-prefix). Try
                    // attaching the tone to the combined surface
                    // first, falling back to the candidate-only
                    // attachment when that doesn't apply.
                    if let toned = Self.applyBareConsonantToneFromTail(
                        candidateSurface: candidate.surface,
                        tail: candidateTail
                    ) {
                        let tonedSurface = leadingLiteral + digitPrefix + toned.surface + toned.remainder
                        if seen.insert(tonedSurface).inserted {
                            expanded.append(Candidate(
                                surface: tonedSurface,
                                reading: fullReading,
                                source: candidate.source,
                                score: candidate.score
                            ))
                        }
                    } else if let split = Self.splitTrailingComposedTaggedTone(candidateTail),
                              !split.body.isEmpty {
                        // TASK-049: the right-shrink probe peeled a
                        // longer tail (`+ka:`-shape from
                        // `ka+ka+ka:`) which the tail composer
                        // rendered as Myanmar body + trailing tone
                        // marker. Treat the candidate's combined
                        // surface (candidate.surface + composed-tail
                        // body) as the toned target and attach the
                        // scalar at its end, instead of dropping
                        // the tone or wedging it as a literal.
                        let combined = candidate.surface + split.body
                        if let toned = Self.applyBareConsonantToneFromTail(
                            candidateSurface: combined,
                            tail: split.tone
                        ) {
                            let tonedSurface = leadingLiteral + digitPrefix + toned.surface + toned.remainder
                            if seen.insert(tonedSurface).inserted {
                                expanded.append(Candidate(
                                    surface: tonedSurface,
                                    reading: fullReading,
                                    source: candidate.source,
                                    score: candidate.score
                                ))
                            }
                        }
                    }
                    if seen.insert(surface).inserted {
                        expanded.append(Candidate(
                            surface: surface,
                            reading: fullReading,
                            source: candidate.source,
                            score: candidate.score
                        ))
                    }
                }
            }
            mergedWithAffixes = expanded
            // The DP-side path at line ~1302 set `lastHistoryKey` to the
            // composable middle's alias; rewrite it to the full-buffer
            // alias so commits from the affixes branch don't pollute
            // history with the truncated key (task 05 follow-up).
            cacheLock.lock()
            lastHistoryKey = Romanization.aliasReading(displayBuffer)
            cacheLock.unlock()
        }

        let sanitizedAffixed = Self.sanitizeMalformedMyanmarMarks(mergedWithAffixes)
        let sanitizedAffixed2 = Self.sanitizeIndepVowelVirama(sanitizedAffixed)
        // TASK-052: same preserved-surfaces guard as the first
        // sanitize call so the user-respecting two-syllable
        // explicit-`+` parses (`1021 1021 102C` for `a+ar`,
        // `1021 1021 1031 102C 103A` for `a+aw`, …) survive into
        // `mergedWithAffixes` even when the affix-merged candidate
        // list still contains an alias-bearing single-anchor
        // sibling (`1021 101B` for `a+ara`).
        let sanitizedAffixed3 = Self.sanitizeAdjacentIndependentVowels(
            sanitizedAffixed2,
            preservedSurfaces: strictInferredStackOutputs
        )
        let sanitizedAffixed4 = Self.sanitizeDoubledCodaChain(sanitizedAffixed3)
        let sanitizedAffixed5 = Self.sanitizeDigitOrphanAsat(sanitizedAffixed4)
        let sanitizedAffixed6 = Self.sanitizeToneOrphanAsat(sanitizedAffixed5)
        // TASK-069: drop candidates whose surface carries the bare
        // `1021 103A` adjacency (independent vowel `အ` + asat) when
        // a clean sibling exists. The `a*` family (and `aa*`, `aaa*`,
        // `+a*`, `a*<X>`, `<C>+a*`) pre-fix surfaced this orphan
        // adjacency at rank 0 even though the structure has no
        // pronounceable Burmese spelling.
        let sanitizedAffixed6b = Self.sanitizeBareIndepVowelAsat(sanitizedAffixed6)
        let sanitizedAffixed7 = Self.sanitizeInterleavedComposingPunct(sanitizedAffixed6b)
        // TASK-030: drop candidates whose surface carries the multi-
        // cluster-on-single-anchor shape (chained vowel-rule arcs that
        // concatenate two dep-vowel clusters on one base, or same-
        // category dep-vowel duplicates within a single base run).
        let sanitizedAffixed8 = Self.sanitizeMultiClusterOnSingleAnchor(sanitizedAffixed7)
        // TASK-060: drop candidates whose surface concatenates a
        // prior syllable's dep-vowel cluster with a fabricated
        // `1021<single dep-vowel>` syllable produced by the
        // tail-compose path (e.g. `kou` right-shrunk to `ko` + tail
        // `u` → `ကို + အူ` = `1000 102D 102F 1021 1030`).
        var sanitizedWithAffixes = Self.sanitizePhantomMidAnchor(sanitizedAffixed8)
        // TASK-060: when the right-shrink probe dropped composing
        // letters (e.g. `kou` → prefix `ko` + tail `u`), the engine
        // composes the prefix and tail separately; the parser's
        // top-1 of the FULL buffer (the canonical
        // `<C><102D 102F><101A 103A><1026>` ya-asat-closer + 1026
        // shape) never enters the candidate set. Acceptance
        // criterion #2 of the task requires the clean form to be
        // reachable somewhere in the panel. Inject the parser
        // top-K parses of the un-shrunk buffer when (a) the
        // right-shrink dropped composing letters, (b) at least one
        // parse has `legalityScore > 0`, and (c) its surface (with
        // affixes) is not already present. Restricted to the
        // composing-letter-drop case so trailing-punct / digit
        // right-shrinks (`kou.`, `kouka`) — which already go
        // through the regular full-buffer path — are unaffected.
        // Restrict to short drops (1-2 chars) to avoid the
        // parse-on-every-keystroke cost on garbage inputs where the
        // right-shrink probe peels long unparseable tails. The
        // bug-shape signature requires only a single trailing
        // non-standalone vowel rule (`u`, `i`, …) to be peeled, so
        // the short-drop gate keeps the injection cheap.
        let shouldInjectFullBufferParses = !droppedTail.isEmpty
            && droppedTail.count <= 2
            && droppedTailHasComposingChars
            && !droppedTailHasComposingPunctuation
            && !preTrimmedNormalized.isEmpty
            && sanitizedWithAffixes.contains { c in
                Self.candidateSurfaceCarriesOrphanAnchorAfterCluster(c.surface)
            }
        if shouldInjectFullBufferParses {
            let fullParses = parser.parseCandidates(
                preTrimmedNormalized,
                maxResults: 8,
                isFullBuffer: true
            )
            let existingSurfaces = Set(sanitizedWithAffixes.map(\.surface))
            for parse in fullParses where parse.legalityScore > 0 {
                let cleanSurface = Self.correctAaShape(parse.output)
                guard SyllableParser.scanOutputLegality(cleanSurface) else { continue }
                guard !Self.surfaceContainsPhantomMidAnchor(cleanSurface) else { continue }
                let composed = leadingLiteral + digitPrefix + cleanSurface + literalTail
                guard !existingSurfaces.contains(composed) else { continue }
                sanitizedWithAffixes.append(Candidate(
                    surface: composed,
                    reading: displayBuffer,
                    source: .grammar,
                    score: Double(parse.score)
                ))
            }
        }
        let finalCandidates: [Candidate]
        if leadingLiteral.isEmpty,
           digitPrefix.isEmpty,
           literalTail.isEmpty,
           droppedTailHasAsciiLetters {
            // The right-shrink probe dropped one or more ASCII letters
            // that didn't compose into Myanmar; those letters get
            // re-appended verbatim onto each candidate. We still want
            // to drop pure-ASCII junk (`fox`, `xyz`), but a surface
            // that mixes Myanmar with a literal ASCII tail (`အဘc`,
            // `အောင်c`, `ကားbc`) is a partial composition the user can
            // act on — leave it in the panel rather than emptying it.
            finalCandidates = sanitizedWithAffixes.filter {
                Self.containsMyanmarSurfaceScalar($0.surface)
                    && SyllableParser.scanOutputLegality($0.surface)
            }
        } else {
            finalCandidates = sanitizedWithAffixes
        }

        return CompositionState(
            rawBuffer: displayBuffer,
            selectedCandidateIndex: 0,
            candidates: finalCandidates,
            committedContext: context
        )
    }

    /// TASK-043 literal-fallback wrapper. Synthesizes a "commit-as-typed"
    /// candidate carrying the user's raw buffer verbatim so the panel
    /// is never empty when the user is typing non-Burmese ASCII (English
    /// words, brand names, mixed-script abbreviations).
    ///
    /// Position uses a single signal for performance: the count of
    /// ASCII a–z letters surviving in the rank-0 candidate surface,
    /// divided by the raw buffer length. The two signals the resolved
    /// policy describes (parser-acceptable prefix length and rank-0
    /// ASCII-letter content) agree in practice — when the parser can't
    /// accept much of the buffer, the engine's pipeline echoes the
    /// unconverted ASCII letters into the rank-0 surface, so the
    /// rank-0 ASCII ratio already captures both cases. Reusing the
    /// engine's already-rendered output avoids a second per-keystroke
    /// `parseLongestAcceptablePrefix` walk on the raw buffer (which
    /// adds ~50% to garbage-input latency in the bench).
    ///
    /// Layout rules:
    ///   - `candidates.isEmpty` → literal is the only candidate.
    ///   - rank-0 surface ASCII-letter ratio ≥ 0.5 → literal at rank 0
    ///     (existing literal promoted if already present elsewhere
    ///     in the list).
    ///   - otherwise → literal appended at the bottom.
    ///
    /// Skipped entirely when the rank-0 candidate already has source
    /// `.lexicon`: a lexicon hit signals intentional Burmese composition,
    /// so cluttering the panel with a romanization echo would degrade
    /// UX. Skipped (no insertion) when the literal surface already
    /// exists somewhere in the panel and the ratio doesn't promote it.
    internal func injectLiteralFallback(
        state: CompositionState,
        rawBuffer: String
    ) -> CompositionState {
        guard !rawBuffer.isEmpty else { return state }
        // Carve-out: lexicon hit at rank 0 means the user is composing a
        // known dictionary word — don't echo the romanization back.
        let firstCandidate = state.candidates.first
        if firstCandidate?.source == .lexicon { return state }

        // Hot path: empty panel → literal is the only candidate.
        if firstCandidate == nil {
            var newState = state
            newState.candidates = [Candidate(
                surface: rawBuffer,
                reading: rawBuffer,
                source: .grammar,
                score: 0
            )]
            return newState
        }

        // Hot path: rank-0 surface already equals the raw buffer
        // (e.g. the engine echoed the raw buffer back as its only
        // candidate, which is common for pure-ASCII garbage and
        // mid-buffer-digit shapes). Nothing to do.
        if firstCandidate?.surface == rawBuffer {
            return state
        }

        // How much of the rank-0 candidate's surface is still raw
        // ASCII a–z letters? When the engine's punct-split /
        // digit-extract / right-shrink pipelines render a
        // Myanmar-anchored surface (`123kya` → `၁၂၃ကျ`,
        // `ka.tar` → `က.တာ`, `kac` → `ကc`), the rank-0 ASCII-letter
        // count is low and the literal must NOT take rank 0 — it
        // appends instead. The scan exits early once the count
        // exceeds half the raw buffer length: for the common pure-
        // Myanmar rank-0 path it returns immediately on the first
        // non-ASCII scalar.
        let rawCount = rawBuffer.count
        let asciiThreshold = (rawCount + 1) / 2
        let topAsciiLetters = topAsciiLetterCountAtLeast(
            in: firstCandidate!.surface,
            threshold: asciiThreshold
        )
        let asciiRatioMet = rawCount > 0 && topAsciiLetters >= asciiThreshold

        // TASK-047: the ASCII-letter ratio above misses two buffer
        // classes:
        //
        //   Class A — sanitizer-fallback-retained illegal Myanmar.
        //   When every Myanmar candidate fails an existing
        //   structural-legality predicate, the sanitizer's
        //   "preserve violators when nothing clean exists" path
        //   keeps the violator at rank 0 even though the engine
        //   itself flagged it as illegal. The ASCII proxy returns
        //   0 (the surface is pure Myanmar) and the literal is
        //   appended at the bottom — so the user sees an illegal
        //   Myanmar shape on top of the panel. Detect by re-
        //   running the sanitizer predicates against the rank-0
        //   surface; promote literal to rank 0 when any flag.
        //
        //   Class B — extreme right-shrink collapse. Pathological
        //   buffers (`kaaaaaaaaa`, `k+k+k+k+k+k`, `aaaaa`) leave
        //   a rank-0 surface of one or two scalars because the
        //   right-shrink probe peels off the unparseable tail. The
        //   surface is structurally legal but semantically loses
        //   60–80% of the keystrokes. Detect by comparing rank-0
        //   scalar count against the buffer character count: when
        //   the scalar count is less than half the buffer count
        //   AND the buffer is at least 5 characters, promote the
        //   literal to rank 0. The 5-character floor keeps short
        //   well-behaved buffers (`kya`, `kac`, `aungc`) on the
        //   ASCII-ratio path.
        let topSurface = firstCandidate!.surface
        let class_A_violation = isClassALiteralPromotionTrigger(
            surface: topSurface,
            rawBuffer: rawBuffer
        )
        let class_B_collapse: Bool = {
            // Floor: short buffers don't get Class B treatment. Real
            // Burmese composition often produces small surfaces from
            // small buffers (e.g. `kya` → `ကျ`, `kac` → `ကc`); the
            // floor keeps those on the ASCII-ratio path.
            guard rawCount >= 5 else { return false }
            // Compute the pathological-collapse signals: long
            // same-letter run, separator-bound repetition shape,
            // and (after the collapse-ratio gate) the rank-0
            // surface dropped most of the buffer's keystrokes.
            //
            // The set of distinct non-separator characters used to
            // gate Class B at `count <= 2`. That gate excluded a
            // family of buffers that match every other Class B
            // signal — short consonant-cluster prefixes followed
            // by a long same-letter run (`thaaaaaa`, `myaaaaaa`,
            // `mnyaaaaa`, `tha+a+a+a+a+a+a+a`) carry 3+ distinct
            // letters even though the bulk of the buffer is one
            // repeating letter. The collapse-ratio gate
            // (`scalarCount * 3 < rawCount`) and the same-letter-
            // run gate (`maxSameLetterRun >= 5`) together already
            // identify these as pathological; the distinct-char
            // ceiling is dropped to cover them. Task 50.
            var distinctContentChars: Set<Character> = []
            var separatorCount = 0
            var maxSameLetterRun = 0
            var currentRun = 0
            var lastChar: Character? = nil
            // Track the same-letter run on the *separator-stripped*
            // content as well — buffers like `tha+a+a+a+a+a+a+a`
            // keep resetting the in-buffer run on every `+` even
            // though the underlying letter-only content
            // (`thaaaaaaaa`) has a long run. Both views participate
            // in the shape gate below. Task 50.
            var maxSameLetterRunStripped = 0
            var currentRunStripped = 0
            var lastCharStripped: Character? = nil
            for ch in rawBuffer {
                let isSeparator = ch == "+" || ch == "'"
                    || ch == ":" || ch == "." || ch == "*"
                if isSeparator {
                    separatorCount += 1
                    currentRun = 0
                    lastChar = nil
                } else {
                    distinctContentChars.insert(ch)
                    if ch == lastChar {
                        currentRun += 1
                    } else {
                        currentRun = 1
                        lastChar = ch
                    }
                    if currentRun > maxSameLetterRun {
                        maxSameLetterRun = currentRun
                    }
                    if ch == lastCharStripped {
                        currentRunStripped += 1
                    } else {
                        currentRunStripped = 1
                        lastCharStripped = ch
                    }
                    if currentRunStripped > maxSameLetterRunStripped {
                        maxSameLetterRunStripped = currentRunStripped
                    }
                }
            }
            // Collapse threshold. The default is `3 * scalar_count
            // < buffer_count` (≥67% loss): catches `aaaaa` 5→1,
            // `kaaaaaaaaa` 10→2, `k+k+k+k+k+k` 11→3 while sparing
            // borderline `kaakaa` (6→2, max-run=2, blocked by the
            // same-letter-run shape gate anyway) and well-behaved
            // Burmese (`tablet` 6→5, `aungc` 5→6, `kya` 3→2).
            //
            // When the buffer carries a long same-letter run
            // (≥5 letters in a row, ignoring separators), the
            // pathological signal is strong enough that 50% loss
            // (`2 * scalar_count < buffer_count`) is the right
            // pivot — that catches the consonant-prefix +
            // long-vowel-run family `myaaaaaa` 8→3, `kyaaaaaa`
            // 8→3, `mnyaaaaa` 8→3, `mngaaaaa` 8→3, `akhaaaaa`
            // 8→3 (TASK-050). The 3-scalar surfaces sit at ratio
            // 2.67×, just below the strict 3× line; the looser
            // gate is gated on `maxSameLetterRunStripped >= 5` so
            // it does not promote redundant-mark shapes like
            // `ka***` (5→2) where the underlying repetition is in
            // the separator-mark count rather than in any letter.
            let scalarCount = topSurface.unicodeScalars.count
            let collapseGatePasses: Bool = {
                if scalarCount * 3 < rawCount { return true }
                if maxSameLetterRunStripped >= 5, scalarCount * 2 < rawCount {
                    return true
                }
                return false
            }()
            guard collapseGatePasses else { return false }
            // Shape gate: the buffer must look like a pathological
            // repetition. Three qualifying shapes:
            //   1. Long same-letter run (≥5): `aaaaa`, `kaaaaaaaaa`,
            //      `mmmmmmm`, `thaaaaaa`. The right-shrink probe
            //      truncates everything past the first syllable.
            //      This shape covers the consonant-prefix +
            //      long-vowel-run family (TASK-050).
            //   2. Long same-letter run on the *separator-stripped*
            //      content (≥5): `tha+a+a+a+a+a+a+a`. Each
            //      separator resets the in-buffer run, but the
            //      underlying letter-only content (`thaaaaaaaa`)
            //      shows the same pathological repetition; the
            //      explicit `+` between every `a` doesn't change
            //      the user-visible collapse outcome (TASK-050).
            //   3. Three-or-more separator-bound short tokens with
            //      one distinct letter: `k+k+k+k+k+k`. Each `k`
            //      attempts a virama stack, but the parser collapses
            //      all but the first pair. The single-distinct-
            //      letter constraint stays because mixed-letter
            //      separator-bound buffers (`ka+ta+pa+...`) are
            //      not pathological — they carry real variety.
            let pathologicalShape = maxSameLetterRun >= 5
                || maxSameLetterRunStripped >= 5
                || (separatorCount >= 3 && distinctContentChars.count <= 2)
            return pathologicalShape
        }()

        // TASK-035: explicit-`+` identical medial-bearing-syllable
        // repetition. When the user types a chain of three or more
        // identical *medial-bearing open* tokens joined by `+`
        // (`kya+kya+kya`, `pwa+pwa+pwa`, `mya+mya+mya`,
        // `ka+kya+kya+kya`, …), the candidate-merge ranking can
        // promote a single-syllable lexicon prefix above the
        // parser's multi-syllable segmentation, dropping the
        // trailing repetitions silently. Detect by:
        //   1. The buffer partitions on `+` into 3+ tokens, AND
        //   2. At least 3 of those tokens are *identical to one
        //      another* AND each carries a `y` / `w` / `h` medial
        //      after the consonant onset (so `ka+ka+ka` is excluded
        //      because `ka` has no medial — that buffer renders
        //      correctly today as a multi-stack `က္ကက`), AND
        //   3. Rank-0 surface scalar count is less than 2x the
        //      number of tokens — i.e. the surface couldn't
        //      possibly contain one syllable per token. A
        //      medial-bearing open syllable (`ကျ`) is 2 scalars,
        //      so the threshold is `scalarCount < 2 * tokenCount`.
        //      This is intentionally tighter than the Class B 3x
        //      ratio so we only fire when most of the buffer's
        //      tokens were dropped.
        // Promotion target: the literal raw buffer at rank 0, so the
        // user has the escape hatch even when the parser refuses to
        // produce the multi-syllable segmentation.
        //
        // The medial-bearing constraint preserves the
        // `MultiStackTrailingTone` family (`ka+ka+ka.`,
        // `ka+ka+ka+ka.`, `k+k+k+k`) which legitimately renders as
        // a multi-stack chain because there is no medial-on-base
        // ambiguity to drive a candidate-merge collapse.
        let class_C_identicalPlusChain: Bool = {
            guard rawCount >= 7 else { return false }
            // Tokenise on `+` only (not on other separators — `:` /
            // `.` / `*` / `'` are tone or punct markers, not stack
            // boundaries).
            let tokens = rawBuffer.split(
                separator: "+",
                omittingEmptySubsequences: true
            ).map(String.init)
            guard tokens.count >= 3 else { return false }
            // A medial-bearing token has `y` or `w` at index ≥ 1
            // (after the initial consonant onset). `h` as a medial
            // is the ha-htoe prefix which appears at index 0
            // (`hma`, `hna`, …) — so check both: a `y`/`w` at
            // index ≥ 1, OR an `h` at index 0 followed by a
            // consonant. The simplest necessary condition for the
            // bug is "token length ≥ 3 AND contains `y` or `w`
            // somewhere AND the token does not contain a coda
            // letter or a tone marker" — every bug-class buffer
            // satisfies this and no negative-control buffer does.
            func isMedialBearingOpen(_ t: String) -> Bool {
                guard t.count >= 3 else { return false }
                // Open means no closing coda letter (`*`, `:`, `.`,
                // and no asat in the reading): the token must end in
                // a vowel letter, typically `a`. Reject tokens
                // carrying tone or close marks.
                guard let last = t.last, last == "a" || last == "e"
                    || last == "o" || last == "u" || last == "i"
                else { return false }
                // Must contain `y` or `w` at index ≥ 1 (medial after
                // consonant), or `h` at index ≥ 1 (which would be a
                // ha-htoe medial after the consonant, e.g. `khw`
                // would not match but `khya` has `y` at index 2).
                let chars = Array(t)
                for i in 1..<chars.count {
                    if chars[i] == "y" || chars[i] == "w" {
                        return true
                    }
                }
                return false
            }
            // Find any *medial-bearing* token that appears 3+ times.
            var counts: [String: Int] = [:]
            for t in tokens where isMedialBearingOpen(t) {
                counts[t, default: 0] += 1
            }
            let hasIdenticalMedialTriple = counts.values.contains { $0 >= 3 }
            guard hasIdenticalMedialTriple else { return false }
            // Surface-collapse check: rank-0 scalar count must be
            // less than 2 * tokenCount — anything that drops half or
            // more of the tokens is a collapse.
            let scalarCount = topSurface.unicodeScalars.count
            return scalarCount < 2 * tokens.count
        }()

        // TASK-039: chained inherent-`a` silent-absorption past the
        // first trailing `a` for buffer-leading vowel-rule shapes.
        // The TASK-016 chained-inherent-a guard at the DP level only
        // rejects a `vowelOnly(inherent-a)` arc whose immediate
        // predecessor ALSO consumed inherent-a AND has a consonant
        // ancestor. For consonant-anchored buffers the second
        // trailing `a` re-renders as `အ` via the right-shrink +
        // literal-tail path (`kaa → ကအ`, `khoutaa → ခေါက်အ`), so
        // the rank-0 scalar count differs from the no-trailing-a
        // form and the strict acceptance criterion is met for
        // n>=2.
        //
        // For BUFFER-LEADING vowel-rule shapes (`iaa`, `iaaa`,
        // `uaa`, `uaaa`, `eaa`, `oaa`, …) there is no consonant
        // ancestor, so neither the TASK-016 guard nor the
        // literal-tail re-render fires. Every trailing `a` past
        // the first chains as inherent-a-empty, producing exactly
        // the same surface as the no-trailing-a form. The user's
        // n>=2 trailing `a`s vanish silently from rank 0.
        //
        // Detect this narrow shape and promote the literal raw
        // buffer to rank 0. The predicate is intentionally tight:
        //
        //   1. Buffer length >= 3 (need at least one vowel-rule
        //      letter + 2 trailing `a`s).
        //   2. Buffer ends in `aa+` (>=2 trailing `a`s).
        //   3. Buffer contains NO consonant letter and NO
        //      separator (`+`, `:`, `.`, `*`, `'`). Only the
        //      ASCII vowel letters `a`, `e`, `i`, `o`, `u`, `y`,
        //      `w`, `r` are admitted — these are the characters
        //      that make up the bare-vowel rules and their
        //      diphthong continuations (`ay`, `aw`, `ar`, `aung`,
        //      `iaung`, etc.). Any other letter signals a
        //      consonant-anchored buffer that is handled by the
        //      TASK-016 / TASK-026 / Class B paths.
        //   4. The full rank-0 surface is non-empty Burmese (not
        //      a literal pass-through; the literal pass-through
        //      already lands at rank 0 via the asciiRatio path).
        //   5. The full rank-0 surface has the SAME scalar count
        //      as the rank-0 surface for the buffer with all
        //      trailing `a`s removed — i.e., the trailing `a`s
        //      contributed nothing to the visible scalar count.
        //
        // Single-trailing-`a` cases (`khia`, `khoa`, `khouta`,
        // `khaunga`) are NOT covered here — they are
        // structurally ambiguous from buffer text alone with
        // legitimate consonant-anchored inherent-vowel forms
        // (`nga`, `kya`, `tha`, `mya`) and with mid-sentence
        // typing prefixes in the corpus. The single-trailing
        // class remains a documented partial gap (filed as
        // TASK-039b for follow-up); the panel still contains the
        // raw-buffer literal at rank >=1, so the user can still
        // commit-as-typed.
        let class_D_chainedInherentATail: Bool = {
            // Bounds: need 1 vowel-rule letter + at least 2
            // trailing `a`s.
            guard rawCount >= 3, rawBuffer.hasSuffix("aa") else { return false }
            // Buffer must contain no separator characters
            // (`+`, `:`, `.`, `*`, `'`). Separator-bearing buffers
            // (`kar:aa`, `min+galarparaa`, …) already produce
            // structurally meaningful Burmese surfaces via the
            // visarga / explicit-stack / mid-buffer-tone paths;
            // those are not bug-class shapes.
            for ch in rawBuffer {
                switch ch {
                case "+", ":", ".", "*", "'":
                    return false
                default:
                    continue
                }
            }
            // Surface must be non-empty Burmese (contain at least
            // one Myanmar scalar). The literal-pass-through case is
            // already handled by the asciiRatioMet path.
            guard !topSurface.isEmpty,
                  topSurface.unicodeScalars.contains(where: { $0.value >= 0x1000 })
            else { return false }
            // Trim ALL trailing `a`s and re-parse. If the trimmed
            // buffer is empty (the full buffer was all-`a`s), this
            // is the leading-A-promotion path (`aa`, `aaa`, `aaaa`
            // → `အ`), which is a TASK-016 carve-out — do NOT
            // promote literal here. Empty trimmed buffer means
            // every character of the input was a trailing `a`.
            var trimmedChars = Array(rawBuffer)
            while trimmedChars.last == "a" {
                trimmedChars.removeLast()
            }
            guard !trimmedChars.isEmpty else { return false }
            let trimmed = String(trimmedChars)
            // Recursively re-parse the trimmed buffer via the
            // pre-fallback path.
            let trimmedState = updateInternal(buffer: trimmed, context: [])
            guard let trimmedTop = trimmedState.candidates.first?.surface,
                  !trimmedTop.isEmpty,
                  trimmedTop.unicodeScalars.contains(where: { $0.value >= 0x1000 })
            else { return false }
            // Restrict to buffer-leading vowel-rule shapes: the
            // trimmed buffer's rank-0 surface must START with an
            // independent-vowel scalar (U+1021..U+102A). This
            // captures the cases where the trimmed buffer is a
            // pure vowel-rule (`i`, `u`, `e`, `o`, `ar`, `in`,
            // `out`, `aung`, `aing`, `ote`, …) without an explicit
            // consonant onset, and is what makes the shape bug-
            // class — the TASK-016 / Class B paths cannot
            // re-render the trailing `a`s as a literal `အ` because
            // there is no consonant ancestor in the parser chain.
            // Consonant-anchored buffers (`kaa → ကအ`,
            // `khoutaa → ခေါက်အ`) start with U+1000..U+1020 and
            // already have their trailing `a`s rendered via
            // TASK-016, so the strict acceptance criterion (rank-0
            // scalar count differs from no-trailing-`a` baseline)
            // is met without any literal-fallback help.
            guard let firstScalar = trimmedTop.unicodeScalars.first,
                  (0x1021...0x102A).contains(firstScalar.value)
            else { return false }
            // Bug-class signal: trimmed and full surfaces have
            // the SAME scalar count — the trailing `a`s emitted
            // nothing visible.
            return trimmedTop.unicodeScalars.count
                == topSurface.unicodeScalars.count
        }()

        let placeAtRankZero = asciiRatioMet
            || class_A_violation
            || class_B_collapse
            || class_C_identicalPlusChain
            || class_D_chainedInherentATail

        var candidates = state.candidates
        if placeAtRankZero {
            if let idx = candidates.firstIndex(where: { $0.surface == rawBuffer }) {
                // Already present (e.g. emitted by
                // `digitOrLiteralFallback` for trailing-digit shapes
                // like `comp2`); promote to rank 0 so the ratio
                // threshold is honoured.
                if idx > 0 {
                    let existing = candidates.remove(at: idx)
                    candidates.insert(existing, at: 0)
                }
            } else {
                candidates.insert(Candidate(
                    surface: rawBuffer,
                    reading: rawBuffer,
                    source: .grammar,
                    score: 0
                ), at: 0)
            }
        } else if !candidates.contains(where: { $0.surface == rawBuffer }) {
            // Myanmar-leading panel: append only when not already
            // present anywhere in the list.
            candidates.append(Candidate(
                surface: rawBuffer,
                reading: rawBuffer,
                source: .grammar,
                score: 0
            ))
        }

        var newState = state
        newState.candidates = candidates
        return newState
    }

    /// TASK-047 helper. Detect rank-0 Myanmar surfaces that the
    /// engine's structural-legality predicates would flag as
    /// illegal — the "Class A" literal-fallback promotion trigger.
    /// Returns true when:
    ///
    ///   1. The surface fails one of the existing sanitizer
    ///      predicates (`surfaceViolatesIndependentVowelInvariant`,
    ///      `surfaceContainsDoubledCodaChain`,
    ///      `surfaceHasIndepVowelVirama`,
    ///      `isOrphanCombiningMarkSurface`, `isOrphanZwnjMark`).
    ///      These are the same predicates `sanitizeAdjacentIndependentVowels`
    ///      / `sanitizeIndepVowelVirama` / etc. apply, so a true
    ///      return here means the sanitizer's fallback path
    ///      ("preserve violators when nothing clean exists") kept
    ///      a violator at rank 0.
    ///
    ///   2. The buffer is a short vowel-only run (only `a`/`e`/
    ///      `i`/`o`/`u`/`r` letters and no separators) AND the
    ///      surface contains 2+ independent-vowel scalars
    ///      (U+1021..U+102A). The orphan-mark promotion path
    ///      produces multi-anchor surfaces from short vowel-only
    ///      buffers (`uue`, `iauu`, `aaoo`, `iueii`); these are
    ///      legitimate last-resort fallbacks when the sanitizer
    ///      can't find a clean sibling, but they should not
    ///      occupy rank 0 when a literal-buffer commit is
    ///      available. Restricting the rule to vowel-only
    ///      alphabetic buffers preserves legitimate multi-anchor
    ///      surfaces from real consonant-bearing buffers
    ///      (`aungain` → `အောင်အိန်`, `aungaung` →
    ///      `အောင်အောင်`) where the multiple anchors correspond
    ///      to deliberate multi-syllable user input.
    private func isClassALiteralPromotionTrigger(
        surface: String,
        rawBuffer: String
    ) -> Bool {
        // Class A only applies when the user typed a vowel-only
        // alphabetic buffer (`uue`, `iauu`, `aaoo`, `iueii`,
        // `uuar`, …). Buffers with consonant-bearing content
        // (`iipy`, `mingalarpar`, `aung`, `kya`) reach the
        // sanitizer fallback through legitimate parser paths and
        // should not be force-collapsed to the literal even when
        // the rank-0 surface technically violates a structural
        // predicate — those cases reflect mid-buffer partial-typing
        // states whose `1021`-anchor adjacency the LM can resolve
        // once more keystrokes arrive. Buffers with separator
        // characters (`u.aung`, `kar:au`, `aung+aung+aung`,
        // `i:akar`, `kar.akar`) carry deliberate multi-syllable
        // structure and similarly stay on the engine's regular
        // ranking path.
        // TASK-030: bug-class chained vowel-rule arcs (`<C>ay<vowel>`,
        // `<C><vowel><vowel>`, onsetless `<vowel><vowel>`) produce a
        // single-anchor surface whose entire syllable carries two
        // dep-vowel clusters or a same-category duplicate (`ကေိုို`,
        // `ကေီီ`, `ကေူူ`, `အီူူ`, `အူူ`, `အိုိုီ`). The
        // surface is wholly the violator — there is no second
        // syllable for the next keystroke to resolve into — so the
        // literal-buffer commit is the right rank-0 even for
        // consonant-bearing buffers (`kayoo`, `kayii`, `kuoo`,
        // `kioo`, `thayoo`, `ngaii`, …). The wholly-single-anchor
        // gate excludes mid-typing prefixes whose violator sits in
        // an orphan sub-cluster of a multi-anchor surface (those
        // resolve as the user keeps typing — see the
        // `ComprehensiveRanking.sentence_longArticle_literaryInfluence`
        // intermediate prefixes `thueiooz`/`thueiooza`/…). Runs
        // BEFORE the vowel-only-alpha gate so consonant-bearing
        // bug-class buffers reach the promotion path.
        if Self.surfaceIsWhollyMultiClusterOnSingleAnchor(surface) { return true }

        let isVowelOnlyAlphaBuffer = !rawBuffer.isEmpty
            && rawBuffer.allSatisfy { ch in
                ch == "a" || ch == "e" || ch == "i" || ch == "o"
                    || ch == "u" || ch == "r"
            }
        guard isVowelOnlyAlphaBuffer else { return false }

        if Self.surfaceViolatesIndependentVowelInvariant(surface) { return true }
        if Self.surfaceContainsDoubledCodaChain(surface) { return true }
        if Self.surfaceHasIndepVowelVirama(surface) { return true }
        if Self.isOrphanCombiningMarkSurface(surface) { return true }
        if Self.isOrphanZwnjMark(surface) { return true }
        // Vowel-only-buffer multi-anchor gate: catch the orphan-
        // mark promotion residue (`aaoo` → `အိုယ်အိုယ်`,
        // `iueii` → `အည်ဦယ်ဤ`) where the existing sanitizer
        // predicates don't fire because each anchor lives in its
        // own asat-closed cluster.
        var indepVowelCount = 0
        for scalar in surface.unicodeScalars {
            let v = scalar.value
            if v >= 0x1021 && v <= 0x102A {
                indepVowelCount += 1
                if indepVowelCount >= 2 { return true }
            }
        }
        return false
    }

    /// Count of ASCII a–z / A–Z scalars in `surface`, capped at
    /// `threshold + 1` so the caller can early-decide whether the
    /// count meets a threshold without paying for the full scan.
    /// Used by the literal-fallback positioning heuristic — for the
    /// common pure-Myanmar rank-0 path the threshold is never
    /// reached and the helper returns 0 quickly.
    @inline(__always)
    private func topAsciiLetterCountAtLeast(in surface: String, threshold: Int) -> Int {
        var count = 0
        let cap = threshold + 1
        for scalar in surface.unicodeScalars {
            let v = scalar.value
            if (v >= 0x61 && v <= 0x7A) || (v >= 0x41 && v <= 0x5A) {
                count += 1
                if count >= cap { return count }
            }
        }
        return count
    }

    /// Run the inferred-`+` parses for `input`, neutralise the
    /// per-`+` bookkeeping bumps so the inferred parse competes with
    /// the no-`+` parse on real merits, and push the result into
    /// `grammarParses` (skipping outputs already present). Used twice
    /// per buffer when `inferImplicitStackMarkers` returns both a
    /// full-site and a strict-only inferred form.
    internal func ingestInferredParses(
        input: String,
        insertions: Int,
        liberalInsertions: Int,
        vowelRuleLiberalInsertions: Int = 0,
        isFullBuffer: Bool,
        grammarParses: inout [SyllableParse],
        existingOutputs: Set<String>,
        strictInferredStackOutputs: inout Set<String>,
        liberalKinziOutputs: inout Set<String>
    ) {
        let inferredParses = stackInferenceParses(input, isFullBuffer: isFullBuffer)
        for parse in inferredParses
        where !Self.hasInterleavedLatin(parse.output) {
            // Neutralise the bookkeeping bump each injected `+` adds:
            // the parser treats a soft-boundary transition as a new
            // vowel slot, so it contributes +1 `syllableCount` and a
            // per-syllable `legalityScore` step (~+100) regardless of
            // whether the site actually stacked. Reverting both keeps
            // the inferred parse on equal footing with the original
            // no-`+` parse, so the two compete on their real merits
            // (parser score, alias cost, LM) rather than on ghost
            // legality the `+` produced.
            let adjustedCount = max(1, parse.syllableCount - insertions)
            let adjustedLegality = parse.legalityScore > 0
                ? max(1, parse.legalityScore - 100 * insertions)
                : parse.legalityScore
            // Bump rarityPenalty per liberal (cross-class) insertion
            // when the buffer doesn't look like a Pali/Sanskrit
            // transliteration. Cross-class virama stacks are Pali
            // loanword territory; ordinary Burmese compounds like
            // `takmaung`, `pakta`, `kakna` produce the same
            // liberal-only `+` sites and should *not* render with a
            // virama at top. The `r` letter is a reliable Pali
            // transliteration hint — `karma`, `dharma`, `brahma`,
            // `yarpadma` all carry it; the over-generating Burmese
            // compounds typically don't. Buffers with no `r` get a
            // rarity bump that demotes the liberal-stacked form
            // below the no-stack sibling. The stacked form stays in
            // the panel as a lower-ranked option, and `padma` /
            // `vandana` / `ganda`-style Pali loanwords with override
            // entries are unaffected (they're injected at rank 0
            // independently of inference). See task 04.
            let prefixHasPaliR = input.contains("r")
            // Coda-branch liberal sites (e.g. `pakta`, `karma`) — the
            // upper consonant comes from a `<vowel><coda><lower>` shape
            // where the coda is a bare consonant before the vowel
            // letter — get the existing +5/site bump only when there's
            // no Pali `r` hint. The `r` heuristic correctly flags
            // genuine Pali/Sanskrit transliterations (`karma`,
            // `dharma`, `brahma`) where the user wants the stack form.
            // `vowelRuleLiberalInsertions` covers the disjoint
            // "Pali-shape vowel-rule" sites, so we cleanly subtract.
            let codaLiberalInsertions = max(0, liberalInsertions - vowelRuleLiberalInsertions)
            let codaLiberalBump = (codaLiberalInsertions > 0 && !prefixHasPaliR)
                ? 5 * codaLiberalInsertions
                : 0
            // Vowel-rule-upper inference sites in the TASK-006
            // bug class (`kantar`, `pantar`, `tantaw`, `tantar`,
            // `ngantar`, `kantawpar`, `ngantawthi`, `thingyantaw`,
            // ...). The upper consonant (`na` from `an`/`on`/`ain`
            // etc.) was already closed with asat by the preceding
            // vowel rule AND the next syllable carries its own
            // closing letter — clear signals of a native Burmese
            // compound where the asat-closed rendering is canonical.
            //
            // The bug-class detection happens upstream in
            // `inferImplicitStackMarkers` (`isBurmeseCompoundSite`):
            // open post-stack syllables (`atta`, `sanda`, `vandanar`,
            // `mantara`, `tarbandana`, `ratna`, `padma`, ...) are
            // recognised Pali transliteration shapes and are NOT
            // counted toward `vowelRuleLiberalInsertions`. Kinzi
            // sites (nga upper) are also excluded.
            //
            // The Pali-shape demotion is achieved primarily by NOT
            // inserting the stack surface into `strictInferredStackOutputs`
            // (so `bestStrictInferredStackIndex` doesn't lift it to
            // rank 0); the +1/site rarity bump is a secondary
            // tiebreaker that ensures the stacked sibling sorts after
            // the asat-closed rendering when their parser scores
            // happen to align. The bump is small enough to keep the
            // stacked sibling within the candidate panel for users
            // who want to pick it manually.
            let vowelRulePaliShapeBump = vowelRuleLiberalInsertions > 0
                ? 1 * vowelRuleLiberalInsertions
                : 0
            let liberalRarityBump = codaLiberalBump + vowelRulePaliShapeBump
            let adjusted = SyllableParse(
                output: parse.output,
                reading: parse.reading,
                aliasCost: parse.aliasCost + 10 * liberalInsertions,
                legalityScore: adjustedLegality,
                score: parse.score,
                structureCost: parse.structureCost + liberalInsertions,
                syllableCount: adjustedCount,
                rarityPenalty: parse.rarityPenalty + liberalRarityBump
            )
            // TASK-006: Pali-shape vowel-rule sites (`kantar`, `pantar`,
            // `tantaw`, `tantar`, `mantara`, `tarbandana`, `ngantar`,
            // ...) produce a stacked surface that is structurally a
            // valid native virama stack (e.g. `ကန္တာ` = `1000 1014
            // 1039 1010 102C` passes `surfaceHasOnlyNativeViramaStacks`
            // because na+ta is class-3 same-class). Without this guard,
            // the rank-0 promotion at `bestStrictInferredStackIndex`
            // would lift the stacked form to top despite the +12 rarity
            // bump applied below — promotion bypasses the comparator
            // entirely. Treat these the same as the kinzi-from-bare-ng
            // liberal path (`liberalKinziOutputs`): keep them
            // discoverable in the panel but not promoted.
            let isPaliShapeVowelRule = vowelRuleLiberalInsertions > 0
            if !isPaliShapeVowelRule,
               liberalInsertions == 0,
               Self.surfaceHasOnlyNativeViramaStacks(adjusted.output) {
                strictInferredStackOutputs.insert(adjusted.output)
                strictInferredStackOutputs.insert(Self.correctAaShape(adjusted.output))
            } else if (liberalInsertions > 0 || isPaliShapeVowelRule),
                      Self.surfaceHasOnlyNativeViramaStacks(adjusted.output) {
                // Liberal-inferred native-stack kinzi (e.g. diphthong-coda
                // bare-ng collapse): protect from LM pruning so the kinzi
                // sibling is reachable in the panel, but do NOT add to
                // strictInferredStackOutputs — that would trigger rank-0
                // promotion and put kinzi above the open form.
                liberalKinziOutputs.insert(adjusted.output)
                liberalKinziOutputs.insert(Self.correctAaShape(adjusted.output))
            } else if Self.surfaceContainsKinzi(adjusted.output) {
                // TASK-045: an inferred parse whose surface carries a
                // kinzi triple (`1004 103A 1039`) but ALSO carries a
                // user-typed cross-class virama (e.g. `ka+minga` →
                // `က္မင်္ဂ` = `k_m + min_ga`) fails the strict
                // `surfaceHasOnlyNativeViramaStacks` check because of
                // the cross-class `k+m` even though the kinzi part is
                // canonical. Preserve such surfaces from LM-margin
                // pruning so the kinzi-bearing candidate stays
                // reachable in the panel; do not promote them to
                // rank 0 (the cross-class virama still belongs at
                // lower rank).
                liberalKinziOutputs.insert(adjusted.output)
                liberalKinziOutputs.insert(Self.correctAaShape(adjusted.output))
            }
            if !existingOutputs.contains(adjusted.output) {
                grammarParses.append(adjusted)
            }
        }
    }

    internal func stackInferenceParses(
        _ input: String,
        isFullBuffer: Bool
    ) -> [SyllableParse] {
        cacheLock.lock()
        if let idx = stackInferenceParseCache.firstIndex(where: {
            $0.input == input && $0.isFullBuffer == isFullBuffer
        }) {
            let entry = stackInferenceParseCache.remove(at: idx)
            stackInferenceParseCache.insert(entry, at: 0)
            cacheLock.unlock()
            return entry.parses
        }
        cacheLock.unlock()

        let parses = parser.parseCandidates(
            input,
            maxResults: Self.stackInferenceBudget,
            isFullBuffer: isFullBuffer,
            allowLiberalStacks: true
        )

        cacheLock.lock()
        stackInferenceParseCache.insert(StackInferenceParseCache(
            input: input,
            isFullBuffer: isFullBuffer,
            parses: parses
        ), at: 0)
        if stackInferenceParseCache.count > Self.maxStackInferenceParseCache {
            stackInferenceParseCache.removeLast(
                stackInferenceParseCache.count - Self.maxStackInferenceParseCache
            )
        }
        cacheLock.unlock()
        return parses
    }

    /// LRU-cached strict (non-liberal) `parseCandidates`. TASK-051:
    /// the active-tail and window-fallback parses run on the same
    /// input every keystroke when the user holds a steady buffer
    /// (the bench's `vowel_rule_chain_*` scenarios) and per-keystroke
    /// re-parsing dominates latency on chains of nga-asat-emitting
    /// vowel rules. Caching the result by `(input, maxResults,
    /// isFullBuffer)` reduces the steady-state cost to a hash lookup.
    /// LRU-cached `findSyllableSafeSplit`. TASK-051: the search loop
    /// performs up to ~24 candidate-split parser passes when no safe
    /// boundary exists in the active tail (e.g. `aing × N` chains
    /// where every position fails `isImplicitNCodaSplit` /
    /// `isConsonantVowelSplit`). The result depends only on
    /// `(normalized, lowerBound)` so memoising it across keystrokes
    /// turns the steady-state cost into a hash lookup.
    internal func cachedFindSyllableSafeSplit(
        in normalized: String,
        targetTail: Int,
        lowerBound: Int
    ) -> Int {
        cacheLock.lock()
        if let idx = windowSplitCache.firstIndex(where: {
            $0.normalized == normalized && $0.lowerBound == lowerBound
        }) {
            let entry = windowSplitCache.remove(at: idx)
            windowSplitCache.insert(entry, at: 0)
            cacheLock.unlock()
            return entry.split
        }
        cacheLock.unlock()
        let split = Self.findSyllableSafeSplit(
            in: normalized,
            parser: parser,
            targetTail: targetTail,
            lowerBound: lowerBound
        )
        cacheLock.lock()
        windowSplitCache.insert(WindowSplitCache(
            normalized: normalized,
            lowerBound: lowerBound,
            split: split
        ), at: 0)
        if windowSplitCache.count > Self.maxWindowSplitCache {
            windowSplitCache.removeLast(
                windowSplitCache.count - Self.maxWindowSplitCache
            )
        }
        cacheLock.unlock()
        return split
    }

    internal func cachedGrammarParses(
        _ input: String,
        maxResults: Int,
        isFullBuffer: Bool
    ) -> [SyllableParse] {
        cacheLock.lock()
        if let idx = grammarParseCache.firstIndex(where: {
            $0.input == input
                && $0.maxResults == maxResults
                && $0.isFullBuffer == isFullBuffer
        }) {
            let entry = grammarParseCache.remove(at: idx)
            grammarParseCache.insert(entry, at: 0)
            cacheLock.unlock()
            return entry.parses
        }
        cacheLock.unlock()

        let parses = parser.parseCandidates(
            input,
            maxResults: maxResults,
            isFullBuffer: isFullBuffer
        )

        cacheLock.lock()
        grammarParseCache.insert(GrammarParseCache(
            input: input,
            maxResults: maxResults,
            isFullBuffer: isFullBuffer,
            parses: parses
        ), at: 0)
        if grammarParseCache.count > Self.maxGrammarParseCache {
            grammarParseCache.removeLast(
                grammarParseCache.count - Self.maxGrammarParseCache
            )
        }
        cacheLock.unlock()
        return parses
    }

    private static func bestStrictInferredStackIndex(
        in candidates: [Candidate],
        strictInferredStackOutputs: Set<String>
    ) -> Int? {
        var bestIndex: Int?
        for (idx, candidate) in candidates.enumerated()
        where strictInferredStackOutputs.contains(candidate.surface) {
            guard let current = bestIndex else {
                bestIndex = idx
                continue
            }
            let currentCandidate = candidates[current]
            let candidateHasKinzi = surfaceContainsKinzi(candidate.surface)
            let currentHasKinzi = surfaceContainsKinzi(currentCandidate.surface)
            if candidate.score > currentCandidate.score
                || (candidate.score == currentCandidate.score && candidateHasKinzi && !currentHasKinzi) {
                bestIndex = idx
            }
        }
        return bestIndex
    }

    private static func surfaceContainsKinzi(_ surface: String) -> Bool {
        let scalars = surface.unicodeScalars.map(\.value)
        guard scalars.count >= 3 else { return false }
        for idx in 0...(scalars.count - 3)
        where scalars[idx] == 0x1004
            && scalars[idx + 1] == 0x103A
            && scalars[idx + 2] == 0x1039 {
            return true
        }
        return false
    }

    /// TASK-031: discriminator for the explicit-`+` strict-stack
    /// promotion. Returns true when `parseReading` is exactly
    /// `userInput` modulo inherent-vowel `a` characters that the
    /// parser inserts at SPECIFIC positions:
    ///   (a) immediately before a `+` in the user input (the inverse
    ///       of `Engine/InputNormalization::collapseConnectorRuns`'s
    ///       TASK-011 reshape `<C>a+<C>` → `<C>+<C>`, e.g. user
    ///       typed `thin+ga+thin`, engine reshape produces
    ///       `thin+g+thin`, parser rebuilds reading `thin+ga+thin`).
    ///   (b) at the end of the reading (the parser's habit of
    ///       appending the inherent vowel after a trailing bare
    ///       consonant — `yan+gun` → reading `yan+guna`).
    ///
    /// `a`s elsewhere — between two consonants in an onset cluster
    /// (`b+r` interpreted as `ba+r` instead of `bra` with medial-r),
    /// or between a vowel and a consonant in a different
    /// segmentation — are rejected because they represent a parser
    /// segmentation choice that does NOT correspond to the user's
    /// intent. Concretely: for user input `brah+ma`, parse reading
    /// `barah+ma` is rejected (the `a` after `b` is a wrong
    /// segmentation choice), but `vyah+ma` (reading reflects the
    /// medial-ra interpretation) is accepted by exact match.
    ///
    /// Examples:
    /// - userInput=`min+ga`, parseReading=`min+ga` → true (exact match)
    /// - userInput=`yan+gun`, parseReading=`yan+guna` → true (rule (b): trailing `a`)
    /// - userInput=`thin+g+thin`, parseReading=`thin+ga+thin` → true (rule (a): `a` before `+`)
    /// - userInput=`brah+ma`, parseReading=`barah+ma` → false (`a` between `b` and `r`, neither rule applies)
    /// - userInput=`min+ga`, parseReading=`mi2na+ga` → false (contains `2`)
    /// - userInput=`min+ga`, parseReading=`mina+ga` → true (rule (a): `a` before `+` — same as `min+ga` after TASK-011 reshape)
    ///   This last case is intentionally accepted: the parser's
    ///   segmentation `mi+na+ga` produces a surface that is also
    ///   a valid post-`+` interpretation for the user. The kinzi
    ///   tiebreaker in `bestStrictInferredStackIndex` will lift the
    ///   true kinzi parse above this asat-only sibling when both
    ///   are present in the candidate set.
    /// TASK-053: peel a trailing tone-marker (`.`/`:`) and/or digit
    /// run from `userInput`. The right-shrink probe in
    /// `parseLongestAcceptablePrefix` typically strips these into
    /// the literal tail before the parser sees the buffer, so the
    /// parser's reading does not carry them. The
    /// `readingMatchesUserLiteralAcrossInherentVowels` comparator
    /// must compare against the user's pre-tail keystrokes to
    /// recognise that the parse respects the user's explicit `+`
    /// signal.
    ///
    /// The strip preserves the buffer when the trailing tone is
    /// already a vowel-modifier (`u.`, `aw:`) on a composable
    /// suffix — those are picked up by the parser as tone arcs and
    /// land inside the reading. Only chains of `.`/`:`/digits at
    /// the very end are peeled.
    @_spi(Testing) public static func stripTrailingToneAndDigitMarkers(_ userInput: String) -> String {
        var chars = Array(userInput)
        // Peel trailing tone / digit chars one by one. Stop on the
        // first non-tone / non-digit char.
        while let last = chars.last {
            let v = last.unicodeScalars.first?.value ?? 0
            let isAsciiDigit = v >= 0x30 && v <= 0x39
            let isToneMarker = last == "." || last == ":"
            if isAsciiDigit || isToneMarker {
                chars.removeLast()
            } else {
                break
            }
        }
        return String(chars)
    }

    @_spi(Testing) public static func readingMatchesUserLiteralAcrossInherentVowels(
        parseReading: String,
        userInput: String
    ) -> Bool {
        let r = Array(parseReading)
        let u = Array(userInput)
        var i = 0
        var j = 0
        while i < r.count && j < u.count {
            if r[i] == u[j] {
                i += 1
                j += 1
            } else if r[i] == "a" {
                // Allow `a` insertion only at "rule (a)" positions:
                // immediately before a `+` in the reading (which
                // means immediately before a `+` in the user input
                // too, since up to this point the two strings are
                // synchronized on non-`a` characters). This is the
                // inverse of the TASK-011 reshape; any other `a`
                // insertion represents a segmentation choice the
                // user did not type.
                if i + 1 < r.count, r[i + 1] == "+" {
                    i += 1
                } else {
                    return false
                }
            } else {
                return false
            }
        }
        // After consuming all of userInput, any remaining reading
        // characters must be a single trailing `a` (rule (b):
        // parser-appended inherent vowel after a trailing bare
        // consonant). Anything else (`2`, `3`, extra letters from
        // a different segmentation) means the parse picked a
        // different reading than the user typed.
        guard j == u.count else { return false }
        if i == r.count { return true }
        if i == r.count - 1 && r[i] == "a" {
            // TASK-052 narrowing: rule (b)'s trailing-`a` allowance
            // covers parses that appended inherent `a` after a bare
            // trailing CONSONANT (e.g. `yan+gun` → `yan+guna`). When
            // the user input ends with `r`/`w`/`y` AFTER a vowel
            // letter, the user's input is a vowel-rule continuation
            // (`ar`, `aw`, `ay`) and the parser's "consonant + a"
            // re-segmentation is a different parse than what the
            // user typed. Reject those so the exact-match parse
            // (`a+ar` = `1021 1021 102C`) wins over the
            // alias-bearing one (`a+ara` = `1021 101B`).
            if u.count >= 2 {
                let last = u[u.count - 1]
                let prev = u[u.count - 2]
                let vowelLetters: Set<Character> = ["a", "e", "i", "o", "u"]
                let medialLikeLetters: Set<Character> = ["r", "w", "y"]
                if medialLikeLetters.contains(last) && vowelLetters.contains(prev) {
                    return false
                }
            }
            return true
        }
        return false
    }

    /// Commit the currently selected candidate.
    /// Returns the committed surface text: the selected candidate for the
    /// convertible prefix, followed by any unconverted tail from the raw
    /// buffer emitted verbatim.
    public func commit(state: CompositionState) -> String {
        guard !state.candidates.isEmpty,
              state.selectedCandidateIndex < state.candidates.count else {
            return state.rawBuffer
        }
        // Candidate surfaces already include the literal tail (appended in
        // update()), so committing the selection emits both parts together.
        return state.candidates[state.selectedCandidateIndex].surface
    }

    /// Record the user's selection in the history store so it can be
    /// promoted on subsequent compositions. Writes the alias-normalized
    /// lookup key captured by the most recent `update` call — matching what
    /// `lookup` will see next time the same reading is typed. No-op when
    /// learning is disabled or the state has no active selection.
    public func recordSelection(state: CompositionState) {
        guard settings?.learningEnabled ?? true else { return }
        guard !state.candidates.isEmpty,
              state.selectedCandidateIndex < state.candidates.count else {
            return
        }
        let candidate = state.candidates[state.selectedCandidateIndex]
        // History-sourced picks must bump the existing row rather than
        // creating a new shortcut keyed on whatever prefix was typed —
        // otherwise picking a long history entry via a short prefix would
        // pollute the table with partial-key duplicates.
        let key: String
        if candidate.source == .history, !candidate.reading.isEmpty {
            key = candidate.reading
        } else {
            cacheLock.lock()
            key = lastHistoryKey
            cacheLock.unlock()
        }
        guard !key.isEmpty else { return }
        historyStore.record(reading: key, surface: candidate.surface)
    }

    /// Cancel composition: return the raw buffer unchanged.
    public func cancel(state: CompositionState) -> String {
        state.rawBuffer
    }
